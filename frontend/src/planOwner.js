/**
 * Чьё это дерево: курса или шаблона с полки.
 *
 * Зеркало серверного `plans/owning.py`, и зеркало намеренно тонкое — здесь
 * только то, чем владелец **адресуется**: поле и номер. Никаких правил про
 * права и календарь тут нет и быть не должно: их знает сервер, а вторая копия
 * правила на клиенте разошлась бы с первой молча — этим проект уже болел, см.
 * `mirrors/`.
 *
 * Заведено оно ради одной вещи: страница плана открывается на двух видах
 * владельца, а всё, что она делает дальше, одинаково. Пока адресом был
 * `classId`, каждый вызов знал, что владелец — курс, и вторым владельцем
 * пришлось бы править два десятка мест.
 */

export const ofCourse = (id) => ({ field: 'course', id })

export const ofTemplate = (id) => ({ field: 'template', id })

/** `course=7` либо `template=3` — то, что уходит в строку запроса. */
export const ownerQuery = (owner) =>
  `${owner.field}=${encodeURIComponent(owner.id)}`

/** То же телом запроса: `{course: 7}` либо `{template: 3}`. */
export const ownerBody = (owner) => ({ [owner.field]: owner.id })

/**
 * Шаблон отличается от курса ровно там, где речь о календаре.
 *
 * У полки нет ни дат, ни расписания, ни утверждения методистом: план на ней
 * к учебному году не привязан. Спрашивается это на клиенте только затем,
 * чтобы **не ходить** за тем, чего нет, — а не чтобы решать, что можно.
 */
export const isTemplate = (owner) => owner?.field === 'template'

/** Один и тот же владелец: по паре, а не по номеру. */
export const sameOwner = (one, other) =>
  Boolean(one) && Boolean(other) && one.field === other.field && one.id === other.id
