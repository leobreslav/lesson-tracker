/**
 * Время суток в 24-часовой записи: разбор набранного и сборка с датой.
 *
 * Свой разбор нужен потому, что браузерные поля времени (`type="time"`,
 * `type="datetime-local"`) формат выбирают сами — по языку браузера и
 * системы, а не приложения. При английском (США) это AM/PM, и атрибута,
 * который бы это переключил, у поля нет. Школьное же время 24-часовое
 * независимо от языка интерфейса — то же правило, что у первого дня недели.
 *
 * Слов здесь нет, только строки и числа: модуль под узловыми тестами.
 */

const pad = (number) => String(number).padStart(2, '0')

/**
 * Набранное → «ЧЧ:ММ» или `null`, если временем это не является.
 *
 * Разбор щедрый, потому что набирают по-разному и все варианты однозначны:
 * «9:05», «09.05», «9 05», «0905», «905», а «9» и «14» — это ровно час.
 * Отказ из-за формы записи стоил бы человеку второй попытки там, где мы и
 * так поняли, что он имел в виду.
 *
 * AM/PM не разбирается намеренно: «9 pm» — это запись, от которой поле и
 * заведено, и принять её значило бы оставить в интерфейсе оба режима.
 */
export function parseTime(text) {
  const said = String(text ?? '').trim()
  if (!said) return null

  let hours
  let minutes
  const split = said.match(/^(\d{1,2})\s*[:.,\s]\s*(\d{1,2})$/)
  if (split) {
    // «9:5» — не пять минут десятого: минуты пишут двумя цифрами, а одна
    // цифра после двоеточия — недописанное «9:50» или «9:05»
    if (split[2].length !== 2) return null
    hours = Number(split[1])
    minutes = Number(split[2])
  } else if (/^\d{1,2}$/.test(said)) {
    hours = Number(said)
    minutes = 0
  } else if (/^\d{3,4}$/.test(said)) {
    hours = Number(said.slice(0, -2))
    minutes = Number(said.slice(-2))
  } else {
    return null
  }

  if (hours > 23 || minutes > 59) return null
  return `${pad(hours)}:${pad(minutes)}`
}

/** «2026-09-27T14:30» → `{date: '2026-09-27', time: '14:30'}`; пустое — пустые. */
export function splitLocal(value) {
  const [date = '', time = ''] = String(value ?? '').split('T')
  return { date, time: time.slice(0, 5) }
}

/**
 * Дата и время → значение той же формы, что у `datetime-local`.
 *
 * Без даты момента нет, и отдаётся пустая строка: форма по ней и узнаёт, что
 * поле не заполнено. Без времени берётся полночь — дату выбирают первой, и
 * выбранная дата не должна оставаться пустым значением, пока не набрано время.
 */
export const joinLocal = (date, time) => (date ? `${date}T${time || '00:00'}` : '')
