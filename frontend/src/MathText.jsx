import { Suspense, lazy } from 'react'
import { hasMath } from './mathText'

const MathInline = lazy(() => import('./MathInline'))

/**
 * Однострочный текст, в котором могут быть формулы.
 *
 * Название урока хранится как есть — «Формула $\\sin(a+b)$», — и в таблице
 * плана его надо показывать формулой, а не долларами: план читают глазами,
 * и `$\\sin(a+b)$` в сорока строках подряд читается хуже, чем сама формула.
 *
 * Два условия, и оба про цену. Долларов в строке нет — не грузим ничего
 * вовсе: у большинства планов формул в названиях не бывает. Есть —
 * подгружаем KaTeX отдельным куском, а до его приезда показываем **тот же
 * текст** как есть: подстановка «загрузка…» на месте названия дёргала бы
 * всю таблицу.
 */
export default function MathText({ text }) {
  if (!hasMath(text)) return text ?? ''

  return (
    <Suspense fallback={text}>
      <MathInline text={text} />
    </Suspense>
  )
}
