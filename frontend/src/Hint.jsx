import { useId, useState } from 'react'
import { useTranslation } from 'react-i18next'

/**
 * Подсказка в два роста: короткая строка всегда, длинная — по «?».
 *
 * Форма работы объясняет каждое своё поле, и объяснять там есть что: окно
 * времени решает видимость, система оценивания считает отметку по порогам,
 * попытки считаются по задаче. Написанное целиком, всё это давало пять
 * абзацев мелким шрифтом — форму из шести полей приходилось **читать**, а не
 * заполнять, и человек, зашедший поправить название, пролистывал её глазами
 * мимо всего.
 *
 * Поэтому две высоты: строка, которой хватает знающему, и подробности тому,
 * кто здесь впервые. Короткая при этом не сокращение длинной, а её первое
 * предложение по смыслу: если знающему её мало, значит она написана плохо, и
 * лечится это текстом, а не кареткой.
 *
 * **Раскрытие, а не всплывающая подсказка.** `title` у браузера — это
 * `<abbr title=…>`, и он был здесь до нас, ровно с таким же длинным текстом
 * про год обучения. Три беды у него, и все три встречаются каждый день:
 * на сенсорном экране его не вызвать вовсе, с клавиатуры тоже, а длинный
 * текст система обрезает по своему усмотрению. Обычная кнопка с раскрытием
 * этого не умеет — и потому работает везде.
 *
 * Раскрытое не запоминается между открытиями окна намеренно: это не
 * настройка вида, а разовый вопрос «что это значит». Помнить ответ на него
 * должен человек, а не интерфейс.
 */
export default function Hint({ short, more, warning = false }) {
  const { t } = useTranslation()
  const [open, setOpen] = useState(false)
  const id = useId()

  // Блок целиком — один ребёнок формы. Иначе вертикальный ритм окна
  // (`.modal-body form > *`) растащил бы короткую строку и её же
  // подробности на два независимых абзаца, и связь между ними пропала бы
  // ровно тогда, когда она нужна.
  return (
    <div className="hint-block">
      <p className={warning ? 'hint warning' : 'hint'}>
        {short}
        {more && (
          <button
            type="button"
            className="hint-more"
            aria-expanded={open}
            aria-controls={id}
            aria-label={t(open ? 'common.hideExplain' : 'common.explain')}
            onClick={() => setOpen((current) => !current)}
          >
            ?
          </button>
        )}
      </p>
      {more && open && (
        <p className="hint hint-detail" id={id}>
          {more}
        </p>
      )}
    </div>
  )
}
