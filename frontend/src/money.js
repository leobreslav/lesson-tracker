/**
 * Микродоллары -> строка с долларами. Одна дверь на весь интерфейс.
 *
 * Дверей было две, и расходились они в самом важном. Панель трат считала
 * `toFixed(2)`, а вызов стоит доли цента — и строка журнала показывала «$0.00»
 * за чтение, которое денег стоило. Ноль на экране там, где деньги ушли, — это
 * не округление, а неверный ответ: именно по этим строкам решают, стоит ли
 * второй читатель своих денег.
 *
 * Отсюда правило, ради которого модуль и заведён: **сумма, которая не ноль, не
 * показывается нулём.** Знаков берётся столько, сколько нужно, чтобы это
 * выполнялось, начиная с двух: месячному потолку хватает центов, отдельному
 * вызову третий знак и есть вся величина.
 *
 * Доллары, потому что в них выставляют счёт и Anthropic, и Mathpix. Переводить
 * их во что-то другое значит объяснять человеку курс, по которому мы сами не
 * платим.
 */

// Дальше четвёртого знака не идём: там уже не деньги, а шум измерения. Ноль
// на такой сумме честнее длинного хвоста нулей.
const MOST_DIGITS = 4

export function dollars(micros) {
  const value = (Number(micros) || 0) / 1_000_000
  if (value === 0) return '$0.00'

  for (let digits = 2; digits < MOST_DIGITS; digits += 1) {
    if (Number(value.toFixed(digits)) !== 0) return `$${value.toFixed(digits)}`
  }
  return `$${value.toFixed(MOST_DIGITS)}`
}
