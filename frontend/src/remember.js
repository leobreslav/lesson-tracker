import { useEffect, useState } from 'react'

/**
 * Переключатели вида, переживающие перезагрузку.
 *
 * Обычное веб-приложение, ограничений на хранилище нет; чтение и запись
 * обёрнуты в try — в приватном режиме просто не запоминается.
 *
 * Лежит отдельным модулем, потому что флажки разошлись по трём файлам:
 * «Даты», «Недели» и «Свободные» стоят над таблицей и живут в `Plan.jsx`,
 * развёрнутость хвоста свободных слотов нужна только самой таблице, а
 * «Темы уроков» — сводному расписанию.
 */

export function remembered(key, fallback) {
  try {
    const saved = localStorage.getItem(key)
    return saved === null ? fallback : saved === '1'
  } catch {
    return fallback
  }
}

export function remember(key, value) {
  try {
    localStorage.setItem(key, value ? '1' : '0')
  } catch {
    // приватный режим — просто не запоминаем
  }
}

/**
 * Последний выбранный курс — не переключатель вида, а место работы.
 *
 * У учителя музыки полтора десятка курсов, и открывать план всегда на
 * первом по алфавиту значит заставлять его выбирать заново каждый заход.
 * Ключ один на все страницы: работают обычно в одном курсе, и «план 7Б, а
 * работы 5А» — состояние, которого никто не просил.
 */
export function lastChoice(key) {
  try {
    const saved = localStorage.getItem(key)
    return saved === null ? null : Number(saved) || null
  } catch {
    return null
  }
}

export function rememberChoice(key, value) {
  try {
    localStorage.setItem(key, String(value))
  } catch {
    // приватный режим — просто не запоминаем
  }
}

/**
 * Заполненное на странице переживает уход с неё.
 *
 * Фильтр, поиск, выбранная вкладка — то, что человек набрал, чтобы дойти
 * до нужного, а не то, что он смотрит. Уходя отсюда на страницу занятия и
 * возвращаясь «назад» в браузере, он получал чистую форму и набирал всё
 * заново: приложение одностраничное, страница при уходе размонтируется, и
 * состояние её компонентов пропадает вместе с ней.
 *
 * Хранится это в `sessionStorage`, а не в `localStorage`, и разница
 * существенная: набранный фильтр живёт, пока открыта **вкладка**. Завтра
 * утром человек открывает работу с чистого листа, а не с позавчерашним
 * «только 7Б» — и это ровно то, чего от фильтра ждут. Переключатели вида
 * (`remembered`) и последний курс (`lastChoice`), наоборот, живут в
 * `localStorage`: это не поза за работой, а настройка.
 *
 * Значение возится через JSON, поэтому в нём должны лежать простые вещи:
 * `Set` и `Map` доедут пустыми. Список — можно.
 */
export function kept(key, fallback) {
  try {
    const saved = sessionStorage.getItem(`kept.${key}`)
    return saved === null ? fallback : JSON.parse(saved)
  } catch {
    // приватный режим или испорченная запись — начинаем с чистого
    return fallback
  }
}

export function keepIt(key, value) {
  try {
    sessionStorage.setItem(`kept.${key}`, JSON.stringify(value))
  } catch {
    // приватный режим — просто не запоминаем
  }
}

/**
 * `useState`, переживающий уход со страницы.
 *
 * Запись идёт эффектом, а не внутри установщика: установщик зовут и с
 * функцией (`setValue((current) => …)`), и тогда нового значения в момент
 * вызова ещё нет — записать пришлось бы результат, посчитанный вторым
 * местом, то есть завести вторую копию правила обновления.
 */
export function useKept(key, initial) {
  const [value, setValue] = useState(() => kept(key, initial))

  useEffect(() => {
    keepIt(key, value)
  }, [key, value])

  return [value, setValue]
}
