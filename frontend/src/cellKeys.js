/**
 * Стрелки в ряду клеток с баллами: когда курсор уходит в соседнюю клетку.
 *
 * Ряд клеток под шапкой листа заполняют подряд, слева направо, и рука при
 * этом лежит на клавиатуре: вписал балл, перешёл к следующей. Мышью это
 * шестнадцать прицеливаний на страницу и восемьдесят страниц на пачку.
 *
 * Правило одно, и оно то же, что в электронных таблицах: стрелка уводит в
 * соседнюю клетку, когда **внутри своей идти уже некуда**. Пока курсор стоит
 * посреди числа, стрелка двигает его по числу — иначе поправить вторую цифру
 * было бы нельзя, не уехав из клетки.
 *
 * Слов здесь нет, только числа: модуль под узловыми тестами.
 */

/**
 * В какую клетку уйти по нажатию — её номер или `null`, если остаться.
 *
 * `start` и `end` — границы выделения в поле, `length` — длина текста.
 *
 * **Выделенное целиком считается краем в обе стороны.** Придя в клетку
 * стрелкой, человек застаёт её содержимое выделенным: так набранная цифра
 * заменяет прежнюю, а не приписывается к ней. Считай мы выделение «курсором
 * внутри», первая стрелка снимала бы его, и на каждую клетку уходило бы два
 * нажатия вместо одного — то есть клавиатура оказалась бы медленнее мыши.
 *
 * За край ряда стрелка не уводит: перескок из последней клетки в первую
 * читался бы как промах, а не как помощь.
 */
export function neighbour({ key, start, end, length, position, count }) {
  if (key !== 'ArrowLeft' && key !== 'ArrowRight') return null
  // положение курсора неизвестно — значит и решать не по чему: поле не из
  // тех, что его отдают, и лучше не делать ничего, чем увести наугад
  if (start === null || start === undefined || end === null || end === undefined) {
    return null
  }

  const whole = start === 0 && end === length
  const collapsed = start === end

  if (key === 'ArrowLeft') {
    const atEdge = whole || (collapsed && start === 0)
    return atEdge && position > 0 ? position - 1 : null
  }

  const atEdge = whole || (collapsed && end === length)
  return atEdge && position < count - 1 ? position + 1 : null
}

/**
 * Набранное в клетке — только цифры, не длиннее двух.
 *
 * Поле текстовое, а не числовое, и это ради стрелок: у числового поля
 * браузер не отдаёт положение курсора, и правило выше было бы не по чему
 * считать. Взамен приходится самим не пускать в клетку буквы — числовое поле
 * делало это за нас. Двух знаков хватает: балл за задачу не бывает больше 99.
 */
export const digits = (text) => String(text ?? '').replace(/\D/g, '').slice(0, 2)
