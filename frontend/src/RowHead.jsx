/**
 * Подпись ряда сетки: номер урока и время звонка под ним.
 *
 * Две сетки расписания — неделя (`WeekGrid.jsx`) и день (`DayGrid.jsx`), —
 * и подпись ряда у них обязана быть одной и той же: это один и тот же
 * школьный час, просто показанный с разных сторон. Разметка тут и стояла
 * дважды, слово в слово, и в первую же правку одна копия осталась бы
 * прежней.
 *
 * **Номер сверху, время под ним одной строкой.** Стояли они рядом — номер
 * слева, время справа в две строчки, — и читалось это как дробь: «1 08:20 /
 * 09:05». Час занимает промежуток, а промежуток пишут одной горизонталью и
 * через дефис; ряд после этого подписан временем, а не двумя числами,
 * которые ещё надо сложить в промежуток глазами.
 *
 * Время не переносится (`white-space: nowrap` у `.row-bell`), а колонка
 * номеров подогнана под него по ширине: перенос «08:20-» и «09:05» обратно
 * в две строки вернул бы ровно то, от чего ушли.
 *
 * Звонков школа могла и не заводить — тогда ряд выглядит как раньше, одним
 * номером, и это рабочее состояние, а не пустое место.
 */
export default function RowHead({ number, bell }) {
  return (
    <div className="row-head">
      <span>{number}</span>
      {bell && (
        <em className="row-bell">
          {bell.starts_at}-{bell.ends_at}
        </em>
      )}
    </div>
  )
}
