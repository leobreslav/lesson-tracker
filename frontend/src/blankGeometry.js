/**
 * Геометрия бланка в миллиметрах.
 *
 * Числа здесь и числа в `blank/blank_form.tex` — одно и то же, записанное
 * дважды: печать рисует лист по одним, чтение кропает по другим. Сдвинули
 * метку в шаблоне, забыли тут — кроп уедет мимо, и выглядеть это будет как
 * «модель стала хуже читать», а не как ошибка вёрстки. Сторожит совпадение
 * `tests/blankGeometry.test.js`, который читает сам .tex.
 *
 * Начало координат — левый верхний угол листа A4.
 */

export const PAGE = { width: 210, height: 297 }

/** Метки по углам листа: центры. Ими выпрямляется страница целиком. */
export const CORNERS = {
  topLeft: { x: 8, y: 8 },
  topRight: { x: 202, y: 8 },
  bottomLeft: { x: 8, y: 289 },
  bottomRight: { x: 202, y: 289 },
}

/**
 * Область, по которой шапку **ищут и оценивают**.
 *
 * Ровно та, что обнята метками (8, 27 и 39 мм): гомография подпёрта ими, и
 * счёт совпадения с сеткой считается там, где ошибка выпрямления наименьшая.
 *
 * По бокам запас в пару миллиметров: печать и резка бумаги гуляют, а
 * обрезанная по краю клетка читается хуже, чем клетка с полем вокруг.
 */
export const HEADER = { x: 10, y: 8, width: 190, height: 30 }

/**
 * Полоска, которая уезжает на чтение: **от верха листа** до низа сетки.
 *
 * Сверху не режется вовсе. Резать там нечего — над строкой имени напечатано
 * только поле, — зато промах кропа вверх стоит дорого: съехала гомография на
 * пару миллиметров, и у строки имени срезан верх букв. Выглядит это не как
 * ошибка кропа, а как испортившееся чтение почерка, и причину будут искать в
 * промпте. Восемь лишних миллиметров бумаги стоят +27% к картинке, то есть
 * доли цента на пачку.
 *
 * **Отдельно от `HEADER`, и это не мелочь.** Пока областью была одна, её
 * расширение вверх утащило за собой и поиск: счёт стал считаться по куску,
 * который метки уже не подпирают, — гомография там продолжена наружу, а на
 * плотно обрезанном скане верха листа может не быть вовсе. На живой пачке
 * после такого расширения две страницы, прочитанные накануне, перестали
 * опознаваться как наш бланк и уехали в «листы условий» — а два ряда условий
 * разрезают пачку. Ищем поэтому там, где надёжно, а картинку берём шире.
 */
export const STRIP = { x: 10, y: 0, width: 190, height: 38 }

/** Сетка баллов: шестнадцать клеток, пятнадцать задач и сумма за страницу. */
export const GRID = {
  x: 12.5,
  y: 19.3,
  cellWidth: 11.5625,
  cells: 16,
  height: 16.5,
  /** Полоса с подписями Q1…Σ pg сверху клетки. */
  labelHeight: 5,
}

/** Поле записи: тетрадная сетка в жирной рамке. */
export const FIELD = { x: 12.5, y: 45, width: 185, height: 230 }

/**
 * QR в правом нижнем углу поля записи.
 *
 * Содержимое у него постоянное и одинаковое на всех листах пачки, поэтому
 * читать его незачем — и мы не читаем. Он отвечает на единственный вопрос:
 * **наш ли это лист**. Лист условий печатают из своих материалов, и нашего
 * кода на нём нет; лист решения — наш, и код на месте, даже если шапка
 * смазана. Без этого «не наш бланк» и «плохое фото нашего листа» неразличимы,
 * а это очень разные события: первое — норма, второе — потерянная работа.
 */
export const QR = {
  size: 16.8,
  modules: 21,
  /** Левые верхние углы обоих кодов, миллиметры от угла листа. */
  at: [
    { x: 15.7, y: 255 },
    { x: 177.5, y: 255 },
  ],
}

/**
 * Начало кода: по нему лист узнаётся как наш.
 *
 * **Семейство и поколение — разные вопросы, и различать их надо порознь.**
 * «Наш ли лист» от поколения не зависит: бланк прошлого выпуска, попавший в
 * пачку нынешнего, — всё равно наш, и сказать об этом надо, а не промолчать.
 * Поэтому сверяется `LT`, а что за ним (`/2/A` у нынешнего, `-BLANK-V1` у
 * прошлого) — это уже ответ на второй вопрос, к геометрии чтения.
 *
 * Проверено на живой пачке прошлого выпуска: декодер находит её код на всех
 * тридцати четырёх страницах, и объявлять их «не нашими» из-за формы строки
 * было бы неправдой.
 */
export const CODE_PREFIX = 'LT'

/**
 * Полоска отдаётся картинкой шириной 1568 точек — ровно столько, сколько
 * оставляет от неё Anthropic. Больше платить смысла нет: он ужмёт сам.
 */
export const STRIP_WIDTH = 1568

export function stripHeight() {
  return Math.round((STRIP_WIDTH * STRIP.height) / STRIP.width)
}

/** Углы полоски в миллиметрах листа — по часовой от левого верхнего. */
export function headerCorners() {
  const { x, y, width, height } = HEADER
  return [
    { x, y },
    { x: x + width, y },
    { x: x + width, y: y + height },
    { x, y: y + height },
  ]
}

/** Углы листа по меткам — по часовой от левого верхнего. */
export function sheetCorners() {
  const { topLeft, topRight, bottomRight, bottomLeft } = CORNERS
  return [topLeft, topRight, bottomRight, bottomLeft]
}

/**
 * Где стоит сетка баллов **внутри полоски**, в долях её ширины.
 *
 * Нужно это экрану: под полоской рисуется ряд полей для тех же шестнадцати
 * клеток, и стоять они должны колонка в колонку с напечатанными. Считать это
 * на глаз нельзя — полоска шире сетки на пару миллиметров с каждой стороны, —
 * а вписать проценты руками значит завести третье место, где живут те же
 * миллиметры. Здесь они одни.
 */
export function gridInStrip() {
  return {
    left: (GRID.x - STRIP.x) / STRIP.width,
    width: (GRID.cells * GRID.cellWidth) / STRIP.width,
  }
}

/**
 * Строка имени: от верха листа до подписей сетки.
 *
 * Уезжает она на чтение отдельной картинкой — вместе с плитками клеток, но
 * своей полосой сверху: имя пишут поперёк всей ширины, и резать его на куски
 * нечего.
 */
export function nameRow() {
  return { x: STRIP.x, y: STRIP.y, width: STRIP.width, height: GRID.y - STRIP.y }
}

/**
 * Одна клетка сетки баллов, без подписи над ней.
 *
 * **Клетки режет браузер, а не модель.** Гомография у нас уже есть, и по ней
 * известно с точностью до миллиметра, где кончается Q14 и начинается Q15 —
 * то есть ровно то, что модель делала на глаз и в чём ошибалась: балл из Q15
 * уезжал в сумму, а вся строка — на клетку влево. Спрашивать её об этом
 * незачем, когда ответ посчитан.
 */
/**
 * Отступ от краёв клетки, миллиметры.
 *
 * Клетка резалась **вместе с печатными границами**, и вместе с ними в плитку
 * заглядывала соседняя. На живой пачке этого хватило: у пустой Q6 читалась
 * единица — в кроп попал хвост двойки, написанной в Q5. Клетка при этом пустая,
 * и ошибка молчаливая: балл появляется там, где на бумаге ничего нет.
 *
 * Миллиметр — это чуть меньше десятой доли клетки: печатная граница (0.2 мм) и
 * промах выпрямления в неё укладываются, а цифра пишется посередине и обрезки
 * не замечает.
 */
export const CELL_INSET = 1

export function cellRect(index) {
  return {
    x: GRID.x + index * GRID.cellWidth + CELL_INSET,
    y: GRID.y + GRID.labelHeight + CELL_INSET,
    width: GRID.cellWidth - CELL_INSET * 2,
    height: GRID.height - GRID.labelHeight - CELL_INSET * 2,
  }
}

/** Как зовётся клетка на бланке: Q1…Q15 и сумма за страницу. */
export function cellLabel(index) {
  return index === GRID.cells - 1 ? 'SUM' : `Q${index + 1}`
}
