/**
 * Область, по которой шапку **ищут и оценивают**.
 *
 * Ровно та, что обнята метками (8, 27 и 39 мм): гомография подпёрта ими, и
 * счёт совпадения с сеткой считается там, где ошибка выпрямления наименьшая.
 *
 * По бокам запас в пару миллиметров: печать и резка бумаги гуляют, а
 * обрезанная по краю клетка читается хуже, чем клетка с полем вокруг.
 */
export const HEADER = { x: 10, y: 8, width: 190, height: 30 }

/**
 * Полоска, которая уезжает на чтение: **от верха листа** до низа сетки.
 *
 * Сверху не режется вовсе. Резать там нечего — над строкой имени напечатано
 * только поле, — зато промах кропа вверх стоит дорого: съехала гомография на
 * пару миллиметров, и у строки имени срезан верх букв. Выглядит это не как
 * ошибка кропа, а как испортившееся чтение почерка, и причину будут искать в
 * промпте. Восемь лишних миллиметров бумаги стоят +27% к картинке, то есть
 * доли цента на пачку.
 *
 * **Отдельно от `HEADER`, и это не мелочь.** Пока областью была одна, её
 * расширение вверх утащило за собой и поиск: счёт стал считаться по куску,
 * который метки уже не подпирают, — гомография там продолжена наружу, а на
 * плотно обрезанном скане верха листа может не быть вовсе. На живой пачке
 * после такого расширения две страницы, прочитанные накануне, перестали
 * опознаваться как наш бланк и уехали в «листы условий» — а два ряда условий
 * разрезают пачку. Ищем поэтому там, где надёжно, а картинку берём шире.
 */
export const STRIP = { x: 10, y: 0, width: 190, height: 38 }

