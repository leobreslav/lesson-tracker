import { useId } from 'react'

/**
 * Тумблер: выбор из двух-трёх видов **одним** контролом.
 *
 * До него это были отдельные кнопки-чипы, и читались они как список
 * действий: две таблетки рядом, каждая сама по себе, а какая из них сейчас
 * включена — видно только по заливке. Хуже всего это выглядело там, где
 * подписи разной длины («План» и «Сравнить с эталоном»): ряд получался
 * кривым, и глазами приходилось решать, это один выбор или два действия.
 *
 * Здесь одна рамка, сегменты равной ширины и бегунок, который переезжает к
 * выбранному. Форма сама говорит, что вариантов ровно столько и включён
 * ровно один.
 *
 * Внутри — настоящие радиокнопки, а не кнопки с `aria-pressed`. Три
 * причины, и все три практические: стрелками с клавиатуры выбор ходит сам,
 * читалка объявляет «1 из 2», а сторож рядов (`e2e/tests/controls.spec.js`)
 * меряет высоту **контролов** и на трёх кнопках внутри одной рамки
 * справедливо ругался бы — рост у них по построению меньше соседнего поля.
 *
 * Бегунок ездит трансформацией на свою же ширину, а ширина — доля от числа
 * сегментов: две подписи разной длины занимают одинаковое место, и рамка
 * не пляшет при переключении.
 */
export default function Switch({
  options,
  value,
  onChange,
  label,
  disabled = false,
  className = '',
}) {
  const name = useId()
  const active = options.findIndex((option) => option.value === value)

  /**
   * Нажали в любое место — тумблер переключился.
   *
   * Радиокнопки сами по себе отзываются только на **чужой** сегмент: клик
   * по выбранному ничего не меняет и события не поднимает. Для группы из
   * трёх вариантов это верно, а для тумблера — нет: он выглядит как один
   * орган управления, и нажатие по нему значит «переключи», а не «выбери
   * ровно это». Поэтому у пары вариантов повторное нажатие уводит к
   * соседнему, и то же делает клик по рамке между сегментами.
   */
  const flip = () => {
    if (options.length !== 2 || disabled) return
    const other = options.find((option) => option.value !== value)
    if (other) onChange(other.value)
  }

  return (
    <span
      className={className ? `switch ${className}` : 'switch'}
      role="radiogroup"
      aria-label={label}
      data-active={active < 0 ? 0 : active}
      style={{ '--switch-count': options.length }}
      // только по самой рамке: клик по сегменту разбирает он сам, иначе
      // выбор чужого сегмента тут же откатывался бы назад
      onClick={(event) => {
        if (event.target === event.currentTarget) flip()
      }}
    >
      <span className="switch-thumb" aria-hidden="true" />
      {options.map((option) => (
        <label
          key={String(option.value)}
          className={option.value === value ? 'switch-option active' : 'switch-option'}
        >
          {/* поле прозрачное и растянуто на весь сегмент, а не спрятано в
              угол: нажимают именно по нему, и целиться в невидимый пиксель
              не приходится ни человеку, ни браузерному тесту */}
          <input
            type="radio"
            className="switch-input"
            name={name}
            checked={option.value === value}
            disabled={disabled}
            onChange={() => onChange(option.value)}
            // повторное нажатие на выбранный сегмент: `change` его не
            // поднимает, а переключиться человек просил именно им
            onClick={() => {
              if (option.value === value) flip()
            }}
          />
          {option.label}
        </label>
      ))}
    </span>
  )
}
