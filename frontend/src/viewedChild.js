import { lastChoice, rememberChoice } from './remember'

/**
 * Чьими глазами родитель сейчас смотрит.
 *
 * Одно место на весь клиент — зеркало серверного `families.viewing.subject_of`,
 * и это не совпадение: вопрос «чей экран» один, значит и ответ должен быть
 * один. Экранов у ученика четыре, и родителю нужны все четыре; передавать
 * выбранного ребёнка пропсом через четыре страницы значило бы написать
 * правило четырежды и однажды забыть — забытый экран показал бы данные
 * прошлого ребёнка, а понять это по виду страницы нельзя.
 *
 * Поэтому выбор живёт рядом с запросами: `api.js` подставляет его в
 * ученические адреса сам, а страницы про родителя не знают вовсе и остаются
 * теми же, что у ученика.
 *
 * Помнится в `localStorage`, как последний курс у учителя: это настройка, а
 * не поза за работой, и завтра утром родитель ждёт того же ребёнка, на
 * котором остановился.
 */

const KEY = 'viewedChild'

export function viewedChild() {
  return lastChoice(KEY)
}

export function setViewedChild(id) {
  rememberChoice(KEY, id)
}

/**
 * Хвост запроса: `child=…` или пустая строка.
 *
 * Вид пользователя тут не спрашивается, и это осознанно: у ученика выбора
 * просто нет, а сервер параметр от него не читает вовсе
 * (`subject_of` возвращает его самого). Спрашивать вид означало бы завести
 * второе место, где решается «чей экран», — ровно то, от чего этот модуль.
 */
export function childParam() {
  const id = viewedChild()
  return id ? `child=${encodeURIComponent(id)}` : ''
}

/** Забыть выбор: при выходе, чтобы следующий вошедший не унаследовал чужого. */
export function forgetViewedChild() {
  rememberChoice(KEY, '')
}
