/**
 * Дорога домой из чужой учётки — «войти как» на стенде разработки.
 *
 * Переключение личности перезагружает страницу (вид пользователя решается
 * на входе), поэтому «кем я был» не может жить в состоянии компонента: оно
 * до перезагрузки не доживает. Живёт в `localStorage`, рядом с самим
 * токеном, и это тот же срок жизни — пока не вышли.
 *
 * Без этого «посмотреть чужими глазами» было билетом в один конец: чтобы
 * вернуться, надо было узнать себя в списке из семнадцати человек, где
 * суперпользователь стоит между учителями и ничем не отмечен. Так это и
 * выглядело на стенде — «поменял пользователя и не вижу, как вернуться».
 *
 * Чистый модуль и лежит отдельно от меню намеренно: правил здесь три, и
 * каждое ломается молча. Хранилище передаётся параметром, поэтому его
 * можно проверить узловым тестом, не поднимая браузер.
 */

export const ORIGIN_KEY = 'devSwitch.origin'

const shelf = (storage) => storage ?? globalThis.localStorage

/**
 * Запомнить, кем вошли по-настоящему. Пишется только **первый** раз.
 *
 * Переключился завуч на ученика, оттуда на учителя — «вернуться» должно
 * вести к завучу, а не на шаг назад: это дорога домой, а не история
 * переходов. Второй записью дом бы и потерялся.
 */
export function rememberOrigin(who, storage) {
  if (!who?.email) return false

  try {
    const box = shelf(storage)
    if (box.getItem(ORIGIN_KEY)) return false
    box.setItem(ORIGIN_KEY, JSON.stringify(who))
    return true
  } catch {
    // приватный режим — просто не запоминаем; список никуда не делся
    return false
  }
}

/** Кем вошли по-настоящему, или `null`, если никем не подменялись. */
export function origin(storage) {
  try {
    const saved = shelf(storage).getItem(ORIGIN_KEY)
    const who = saved ? JSON.parse(saved) : null
    return who?.email ? who : null
  } catch {
    // испорченное значение — это «дома не помним», а не повод падать
    return null
  }
}

/**
 * Токен, которым вошли по-настоящему, — им и надо стучаться в дев-дверь.
 *
 * Контур со списком допущенных пускает в эту дверь только своих, а
 * подменившийся ходит уже ученическим токеном: спроси она текущего — и
 * «войти как» работал бы ровно один раз, а обратно человек попадал бы
 * только через выход. `null` значит «подмены не было либо токен не
 * сохранился» — тогда сойдёт и текущий.
 */
export function homeToken(storage) {
  return origin(storage)?.token ?? null
}

export function forgetOrigin(storage) {
  try {
    shelf(storage).removeItem(ORIGIN_KEY)
  } catch {
    // нечего забывать
  }
}

/**
 * Мы дома — значит дороги домой нет; запись о ней стоит забыть.
 *
 * Дом, совпадающий с текущим пользователем, — это не дорога, а запись,
 * пережившая свою базу. Токен в ней при этом мёртвый: стенд пересевают, а
 * базу и вовсе подменяют целиком, и всё, что было выдано прежней, перестаёт
 * существовать. Выход такую запись чистит (`forgetOrigin`), но выходом дело
 * кончается не всегда: умерший токен роняет запрос в 401, человека выкидывает
 * на вход, он заходит заново — и `handleLogout` при этом не звали вовсе.
 *
 * Пока запись лежит, «войти как» стучится в дверь мёртвым токеном, а дверь
 * на контуре со списком допущенных отвечает на анонима 403. Клиент читает
 * этот отказ как «двери здесь нет» и прячет переключатель совсем — то есть
 * пропадает он именно там, где нужен, и выглядит это как закрытый контур.
 *
 * Возвращает `true`, если запись была и её убрали.
 */
export function forgetIfHome(user, storage) {
  const who = origin(storage)
  if (!who || !user?.email || who.email !== user.email) return false

  forgetOrigin(storage)
  return true
}

/**
 * Показывать ли дорогу домой.
 *
 * Не показываем, когда идти некуда: подмены не было или мы уже дома —
 * вернулись своим входом. Кнопка «вернуться к себе», нажатие на которую
 * ничего не меняет, хуже отсутствующей.
 */
export function wayHome(user, storage) {
  const who = origin(storage)
  if (!who) return null
  return user && who.email === user.email ? null : who
}
