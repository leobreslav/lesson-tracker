import { useState } from 'react'
import { remember, remembered } from './remember'

/**
 * Карточка, которая сворачивается. Заголовок и есть переключатель.
 *
 * Заведена ради страницы урока: разделов там пять, и держать пять
 * собственных реализаций свёртки значило бы получить пять слегка разных.
 *
 * **Состояние запоминается** (`remember.js`), и это пересмотр решения,
 * принятого, когда сворачивался один только журнал. Тогда казалось, что
 * свёрнутость — свойство занятия: на новом уроке журнал снова пуст, значит
 * снова закрыт. На пяти блоках видно, что это неправда: закрыть или открыть
 * раздел — привычка человека, а не состояние урока, и учитель, отмечающий
 * посещаемость каждый день, иначе открывал бы её пять раз в день.
 *
 * Умолчание при этом остаётся за экраном: `openByDefault` действует, пока
 * человек ничего не решил сам.
 *
 * `note` — то, что видно **не открывая**: «отмечено 3 из 14». Без него
 * свёрнутый блок означал бы «не знаю, что там», и открывать пришлось бы
 * каждый.
 *
 * `actions` стоят в шапке **рядом** с переключателем, а не внутри него:
 * кнопка внутри кнопки разметкой не разрешена, да и нажатие на «Новая
 * работа» не должно попутно сворачивать раздел. Место у действий одно на
 * все карточки — правый край шапки: под заголовком они читались бы как
 * первая строка содержимого, а не как то, что делают с карточкой.
 *
 * **`empty` — раздел, в котором нечего показывать.** Он рисуется одной
 * строкой: ни каретки, ни тела, ни фразы «тут ничего нет». Пустота
 * занимала столько же места, сколько содержимое, — четыре пустых блока
 * тратили четыре карточки на рассказ об отсутствии, — а сказать про неё
 * достаточно словом в шапке.
 *
 * Действия у пустого раздела при этом **видны**: разворачивать в нём
 * нечего, а добавить файл надо. Прежнее правило «у свёрнутой карточки
 * действий не видно» осталось для непустых: там раскрытие и есть способ
 * добраться до содержимого, и форма, открытая в свёрнутом теле, не видна
 * вовсе.
 */
export default function Collapsible({
  name,
  title,
  note = null,
  actions = null,
  empty = false,
  openByDefault = true,
  children,
}) {
  const key = `lesson.${name}`
  const [open, setOpen] = useState(() => remembered(key, openByDefault))

  const toggle = () => {
    setOpen(!open)
    remember(key, !open)
  }

  const head = (
    <>
      {!empty && <span className="caret">{open ? '▾' : '▸'}</span>}
      <span className="panel-title">{title}</span>
      {note !== null && <span className="hint">{note}</span>}
    </>
  )

  return (
    <section className={empty ? 'panel empty' : 'panel'} data-block={name}>
      <div className="panel-head spread">
        {empty ? (
          <span className="panel-label">{head}</span>
        ) : (
          <button
            type="button"
            className="panel-toggle"
            aria-expanded={open}
            onClick={toggle}
          >
            {head}
          </button>
        )}
        {/* обёртка обязательна: у шапки `space-between`, и два действия
            без неё разъехались бы по её краям */}
        {actions && (open || empty) && (
          <span className="panel-actions">{actions}</span>
        )}
      </div>

      {open && !empty && children}
    </section>
  )
}
