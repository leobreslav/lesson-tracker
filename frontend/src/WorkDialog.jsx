import { useTranslation } from 'react-i18next'
import Modal from './Modal'
import WorkForm from './WorkForm'

/**
 * Окно заведения работы: та же форма, что и на странице правки, но поверх
 * списка.
 *
 * **Окно осталось только созданию, и это решение, а не остаток.** Правка
 * тоже открывалась окном, и жаловались на неё прямо: у работы, которая уже
 * живёт, полей много — задание с картинками, приложенные файлы, окно
 * времени, попытки, оценивание, — и читать их в щёлку поверх страницы
 * неудобно. Правка уехала на свою страницу (`WorkEdit`, `/works/:id/edit`).
 *
 * Заведению окно, наоборот, идёт: заполняют в нём название и две даты, а
 * уводить со списка ради трёх полей — значит терять место, куда человек
 * смотрел. По той же причине окно осталось и на странице занятия, где
 * работу задают, не сходя с урока.
 *
 * Заголовок здесь всегда «новая работа», хотя `work` по ходу дела
 * появляется: первая вставленная картинка заводит работу, чтобы было к чему
 * приложить файл (см. `WorkForm`). Заголовок, меняющийся с «Новая работа»
 * на «Правка» оттого, что человек вставил картинку, называл бы не то, что
 * он делает.
 */
export default function WorkDialog({ onClose, ...form }) {
  const { t } = useTranslation()

  return (
    <Modal onClose={onClose} title={t('works.add')}>
      <WorkForm {...form} onCancel={onClose} />
    </Modal>
  )
}
