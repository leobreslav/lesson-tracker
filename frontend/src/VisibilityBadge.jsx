import { useState } from 'react'
import { useTranslation } from 'react-i18next'

/**
 * Кому видна запись на полке — и переключатель того же вопроса.
 *
 * Состояний два, и названы **оба**. Пометка была одна, «черновик», и
 * отвечала она на половину вопроса: черновик было видно, а опубликованное
 * молчало — то есть «видит вся школа» и «я не знаю, что с этой записью»
 * выглядели одинаково, пустым местом.
 *
 * Форма — `button.badge`: нажатие здесь не действие рядом с состоянием, а
 * само состояние, и повторное возвращает обратно. Ссылкой «Опубликовать»
 * это было в окне полки, и рядом с ней стояла неподвижная плашка — то есть
 * состояние и его переключатель жили в двух разных местах строки.
 *
 * Цвета два, а не один со словом: «только для меня» и «опубликован» — не
 * градации одного, а два положения, и различать их приходится в списке,
 * боковым зрением.
 *
 * Компонент общий на витрину и на окно полки намеренно. Строки там теперь
 * одинаковые, а два ответа на один вопрос в этом проекте расходятся молча —
 * первым разошлось бы слово, вторым цвет.
 *
 * Запросов отсюда не уходит: плашка зовёт `onChange` с **новым** значением,
 * а перечитывание списка и карточки остаётся на странице.
 */
/**
 * `control` — тот же переключатель ростом с кнопку, для ряда действий.
 *
 * Форма остаётся плашкой (скруглённой и в два цвета): это по-прежнему
 * состояние, а не действие рядом с ним. Меняется только рост — в ряду
 * контролов плашка высотой в строку текста прижимается низом к кнопкам и
 * читается съехавшей, о чём говорит и правило «строка формы», и сторож
 * рядов, который на такой высоте справедливо падает.
 */
export default function VisibilityBadge({
  published,
  busy = false,
  onChange,
  control = false,
}) {
  const { t } = useTranslation()

  /*
   * Ожидание ответа плашка держит **у себя**, а не берёт из общего `busy`.
   *
   * Общим оно и было, и наружу выходило морганием: `busy` гасит все кнопки
   * экрана, поэтому от нажатия на одну плашку вздрагивала и синяя кнопка
   * рядом, и все карточки витрины разом. Гасить надо ровно то, что нельзя
   * нажать дважды, — а это сама плашка.
   *
   * `onChange` может ничего не вернуть (например, у вызывающего своё
   * состояние занятости), и тогда ждать нечего: гасить плашку навсегда из-за
   * невозвращённого обещания — худшее, что тут можно сделать.
   */
  const [pending, setPending] = useState(false)

  const toggle = () => {
    const answer = onChange(!published)
    if (!answer || typeof answer.then !== 'function') return

    setPending(true)
    answer.finally(() => setPending(false))
  }

  return (
    <button
      type="button"
      className={`badge showcase-visibility${control ? ' as-control' : ''}${
        published ? '' : ' draft'
      }`}
      disabled={busy || pending}
      /* Ключи литералами, а не тернарником внутри `t()`: сторож словарей
         (`locales.test.js`) читает только форму `t('ключ')`, и спрятанный в
         тернарник ключ перестал бы проверяться — опечатка доехала бы до
         человека сырым `library.visibility.…` на месте подписи. */
      title={
        published
          ? t('library.visibility.hideHint')
          : t('library.visibility.publishHint')
      }
      onClick={toggle}
    >
      {published
        ? t('library.visibility.published')
        : t('library.visibility.draft')}
    </button>
  )
}
