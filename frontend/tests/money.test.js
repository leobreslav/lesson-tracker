/**
 * Показ денег.
 *
 * Под тестами по той же причине, что и геометрия: ошибка тут ничего не роняет
 * и ни слова не пишет в консоль — она показывает «$0.00» там, где деньги
 * потрачены. Отличить «бесплатно» от «округлилось» глазами нельзя, а по этим
 * числам решают, платить ли дальше за второго читателя.
 */

import assert from 'node:assert/strict'
import { test } from 'node:test'

import { dollars } from '../src/money.js'

test('ноль так и говорит', () => {
  assert.equal(dollars(0), '$0.00')
})

test('вызов ценой в доли цента не превращается в ноль', () => {
  // Столько стоит чтение шапки моделью и один запрос к Mathpix. Ровно эти
  // строки журнала и показывались нулём, пока форматтеров было два.
  assert.equal(dollars(2_000), '$0.002')
  assert.equal(dollars(4_000), '$0.004')
})

test('там, где хватает центов, лишних знаков нет', () => {
  assert.equal(dollars(68_000), '$0.07')
  assert.equal(dollars(12_500_000), '$12.50')
  assert.equal(dollars(1_000_000), '$1.00')
})

test('совсем малая сумма показывается четвёртым знаком, а не нулём', () => {
  assert.equal(dollars(400), '$0.0004')
})

test('меньше десятой доли микродоллара — уже не деньги', () => {
  // Дальше четвёртого знака идти некуда, и ноль тут честнее хвоста нулей.
  assert.equal(dollars(40), '$0.0000')
})

test('мусор вместо числа не роняет строку', () => {
  // Ответ сервера может не дойти, и место для суммы на экране уже есть.
  assert.equal(dollars(undefined), '$0.00')
  assert.equal(dollars(null), '$0.00')
  assert.equal(dollars('нет'), '$0.00')
})
