"""
Достаёт ли этот контур до читателя.

Вопрос решается **ответом сервера, а не настройкой**. Настройка отвечала бы на
него вторым голосом: ключ говорит «читатель есть», переменная — «нет», и
разъехаться они могут молча, в день переезда на другой хост. Спрошенный же у
самого сервера ответ не устаревает никогда.

По умолчанию считается, что достаём: это верно для всех контуров, кроме тех,
где не верно, и узнаётся это первой же попыткой.

**Ответ запоминается, и вот почему это не оптимизация.** Пачка — это тридцать
с лишним страниц, каждая своим запросом. Без памяти каждая страница заново
ждала бы, пока попытка упрётся в таймаут; тридцать четыре раза по двадцать
секунд — это одиннадцать минут чистого ожидания, и снаружи это выглядит
зависшим чтением, а не чтением, которое честно сказало «не могу». Узнать один
раз на пачку — то же самое знание, только вовремя.

**Помнится это про каждого читателя порознь**, и не сразу: сперва помнилась
только модель. На живой пачке выяснилось, что с закрытого контура не
достучаться и до распознавателя — и каждая из тридцати четырёх страниц честно
ждала его двадцать секунд, уже прочитав имя другим. Беда у читателей общая,
значит и лекарство общее; разное у них только имя ключа.

Помнится **ненадолго**, потому что отвечает на вопрос о сети, а сеть чинится:
блокировку снимут, прокси поднимут, сервер переедут — и контур обязан сам
вернуться к читателю, без перезапуска и без чьей-либо памяти о том, что
когда-то он до него не достучался.

Память процессная (кэш по умолчанию — `LocMemCache`), и воркеров на проде два:
значит лишних проб бывает две за окно, а не одна. Заводить общий кэш ради
этого не стоит — цена ошибки тут одна лишняя попытка, а не неверный ответ.
"""

from django.core.cache import cache

KEY = "vision:unreachable:%s"

# Через сколько пробовать снова. Десять минут — это «пачку дочитаем без него,
# а следующую попробуем с ним».
RECHECK = 600


def reachable(reader: str) -> bool:
    """Стоит ли вообще пробовать. Ничего не знаем — значит стоит."""
    return not cache.get(KEY % reader)


def remember_unreachable(reader: str) -> None:
    """Не достучались. Остальные страницы пачки не будут ждать зря."""
    cache.set(KEY % reader, True, RECHECK)


def forget(reader: str) -> None:
    """Забыть вердикт: пробовать снова прямо сейчас."""
    cache.delete(KEY % reader)
