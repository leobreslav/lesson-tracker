"""
Достаёт ли этот контур до модели.

Вопрос решается **ответом сервера, а не настройкой**. Настройка отвечала бы на
него вторым голосом: ключ говорит «модель есть», переменная — «модели нет», и
разъехаться они могут молча, в день переезда на другой хост. Спрошенный же у
самого сервера ответ не устаревает никогда.

По умолчанию считается, что модель есть: это верно для всех контуров, кроме
тех, где не верно, и узнаётся это первой же попыткой.

**Ответ запоминается, и вот почему это не оптимизация.** Пачка — это тридцать
с лишним страниц, каждая своим запросом. Без памяти каждая страница заново
ждала бы, пока SDK трижды переспросит и сдастся по таймауту; тридцать четыре
раза по десятку секунд — это чтение, которое выглядит зависшим, а не чтение,
которое честно сказало «не могу». Узнать один раз на пачку — то же самое
знание, только вовремя.

Помнится оно **ненадолго**, потому что отвечает на вопрос о сети, а сеть
чинится: блокировку снимут, прокси поднимут, сервер переедут — и контур обязан
сам вернуться к модели, без перезапуска и без чьей-либо памяти о том, что
когда-то он к ней не достучался.

Память процессная (кэш по умолчанию — `LocMemCache`), и воркеров на проде два:
значит лишних проб бывает две за окно, а не одна. Заводить общий кэш ради
этого не стоит — цена ошибки тут одна лишняя попытка, а не неверный ответ.
"""

from django.core.cache import cache

KEY = "vision:model-unreachable"

# Через сколько пробовать снова. Десять минут — это «пачку дочитаем без
# модели, а следующую попробуем с ней».
RECHECK = 600


def model_reachable() -> bool:
    """Стоит ли вообще пробовать. Ничего не знаем — значит стоит."""
    return not cache.get(KEY)


def remember_unreachable() -> None:
    """Не достучались. Остальные страницы пачки не будут ждать зря."""
    cache.set(KEY, True, RECHECK)


def forget() -> None:
    """Забыть вердикт: пробовать снова прямо сейчас."""
    cache.delete(KEY)
