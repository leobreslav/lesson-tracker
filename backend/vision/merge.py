"""
Два чтения одной полоски -> одно. Поле берётся у того, кто в нём силён.

**Это не голосование и не среднее.** Читатели сильны в разном, и это знание
добыто живыми пачками, а не рассуждением:

- **имя и фамилию** лучше читает языковая модель. Распознаватель видит буквы
  по одной и на рукописном имени ошибается заметно чаще; модель же знает, что
  это имя, и держит слово целиком;
- **клетки с баллами** лучше читает распознаватель. Плитки — это таблица, а
  таблицы он читает отлично: цифра в квадратике не требует понимания, требует
  зрения. Модель же на них сбивается со счёта и путает соседние клетки.

До этого правила читатели считались равноправными, и лучшее, что можно было
сделать с расхождением, — показать его человеку. Теперь у каждого поля есть
хозяин, и человека беспокоят только там, где хозяин может ошибаться.

**Пометка о расхождении при этом остаётся, и это главное.** Приоритет решает,
что **записать**; пометка — о чём **сказать**. Смешивать эти два вопроса
нельзя: правило «имя от модели» не делает модель непогрешимой, оно лишь
говорит, чья версия правдоподобнее. Убери мы пометку — и молчаливая ошибка
вернулась бы ровно в том месте, ради которого второго читателя заводили.

Арбитра здесь нет намеренно. Он перечитывал спорную страницу третьим, дорогим
чтением; правило же отвечает на тот же вопрос точнее и бесплатно, потому что
опирается не на догадку о странице, а на знание о читателях.
"""

from __future__ import annotations

# Что берётся у того, кто силён в почерке. `text` — строка имени, как она
# прочитана: человеку показывают прочитанное, а не наш разбор его на графы.
# `guess` — мнение модели о том, кого она видит из списка класса; у
# распознавателя его не бывает вовсе.
FROM_NAME_READER = ("first_name", "surname", "date", "text", "guess", "model")

# Что берётся у того, кто силён в таблицах.
FROM_CELLS_READER = ("values",)


def take(*, names_from: dict, cells_from: dict) -> dict:
    """
    Собрать чтение страницы из двух: имя от одного, клетки от другого.

    Основой берётся чтение имени, а не пустой словарь: у него есть поля,
    которых у распознавателя не бывает (`guess`), и терять их из-за слияния
    незачем.

    **Пустое поле не перебивает непустого.** «Я этого не увидел» — не то же
    самое, что «там пусто»: распознаватель не разбирает половину плиток на
    бледном скане, и его молчание не должно стирать клетку, которую прочитал
    другой. Поэтому клетки сливаются поштучно, а не списком целиком.
    """
    reading = dict(names_from)

    for field in FROM_CELLS_READER:
        reading[field] = cells(names_from.get(field), cells_from.get(field))

    # Отдельного поля «кем прочитано» тут нет намеренно: ответ уже есть и
    # состоит из двух частей, которые и так доезжают до страницы. Имя читал
    # тот, чьё имя в `model`; клетки — тот, чьё имя в `second.reader`. Третье
    # место с тем же ответом разъехалось бы с ними в первой же правке.
    return reading


def cells(mine: list | None, theirs: list | None) -> list:
    """
    Клетки двух чтений -> клетки страницы. Хозяин — второй, но не любой ценой.

    Берётся значение хозяина клеток; там, где он смолчал, остаётся значение
    другого читателя. Иначе сильный в таблицах читатель, не разобравший
    бледную плитку, стирал бы верно прочитанный балл — то есть приоритет
    работал бы против той самой точности, ради которой заведён.
    """
    mine = list(mine or [])
    theirs = list(theirs or [])
    length = max(len(mine), len(theirs))

    out = []
    for place in range(length):
        ours = mine[place] if place < len(mine) else None
        yours = theirs[place] if place < len(theirs) else None
        out.append(yours if yours is not None else ours)
    return out
