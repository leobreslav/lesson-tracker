"""
Модели и цены — в одном месте, потому что расходятся они молча.

Цена живёт рядом с именем модели: разъехавшись, они дают счёт, который не
сходится с настоящим, а заметить это можно только по выписке от Anthropic
через месяц. Числа — доллары за миллион токенов, вход и выход.

Обновлять при смене прайса. Модель, которой тут нет, к вызову не допускается
вовсе (`price_of` поднимает ошибку): считать расход по нулевой цене — это
тихо снятый потолок.
"""

# Дешёвая, ей читается каждая полоска шапки.
HAIKU = "claude-haiku-4-5-20251001"
# Дорогая и внимательная: ею перечитывается то, что не сошлось.
SONNET = "claude-sonnet-5"

PRICES = {
    HAIKU: (1.0, 5.0),
    SONNET: (3.0, 15.0),
}

# Второй читатель шапки. Не модель и токенов не считает: у Mathpix цена стоит
# на **запросе**, сколько бы текста ни нашлось на картинке.
MATHPIX = "mathpix-text"

# Микродоллары за один запрос. Держать это в `.env` было бы хуже: цена — не
# настройка контура, а факт про сервис, и разъехавшись с ним, журнал трат врёт
# молча.
#
# **$0.002, а не $0.005, и колонку прайса легко перепутать.** Мы зовём
# `v3/text` (Image OCR) и посылаем туда картинку полоски — это первая колонка.
# Соседняя, `v3/pdf` по $0.005 за страницу, про документы целиком, и к нам она
# не относится. Оговорка витрины «картинка больше чем в 12 строк текста может
# считаться по страничному тарифу» нас тоже минует: в шапке пара строк — ещё
# один довод за то, чтобы читателю посылалась узкая полоска, а не лист.
#
# Стояло здесь $0.004 — тариф, каким он был, когда второго читателя заводили.
# Журнал трат от этого не ошибался в опасную сторону, но показывал второго
# читателя вдвое дороже, чем он есть, — то есть врал ровно тому числу, по
# которому решают, платить ли за него дальше.
# Третий читатель, Yandex Vision OCR. Тоже за страницу, а не за токены.
YANDEX = "yandex-ocr"

PER_REQUEST = {
    MATHPIX: 2_000,
    # **Цена тут в чужой валюте, и это единственное такое место.** У Яндекса
    # прайс рублёвый — порядка ₽0.13 за страницу (₽100 за тысячу), — а журнал
    # трат весь в долларах, потому что в них выставляют счёт остальные. Курс
    # взят круглым, ₽100 за доллар, и записан здесь, а не подразумевается:
    # разъехавшись с настоящим, он врёт молча и в одну сторону.
    #
    # Правильный ответ на это — научить журнал хранить валюту, а не держать
    # курс в коде. Пока читатель один рублёвый и суммы копеечные, цена ошибки
    # — доли цента на пачку; когда станет иначе, чинить надо здесь.
    YANDEX: 1_300,
}


def price_of(model: str) -> tuple[float, float]:
    try:
        return PRICES[model]
    except KeyError:
        raise ValueError(f"Unknown model {model!r}: add it to vision/prices.py")


def cost_micros(model: str, input_tokens: int, output_tokens: int) -> int:
    """
    Стоимость вызова в миллионных долях доллара.

    Целые числа, а не float: деньги складываются и сравниваются с потолком, а
    накопленная ошибка сложения float'ов в этом месте — не мелочь.

    Считается по-разному, потому что и продаётся по-разному: у модели цена на
    токенах, у распознавателя — на запросе. Дверь при этом одна: считать
    расход двумя способами в двух местах значит завести два ответа на вопрос
    «сколько школа потратила».
    """
    if model in PER_REQUEST:
        return PER_REQUEST[model]

    in_price, out_price = price_of(model)
    return round(input_tokens * in_price + output_tokens * out_price)
