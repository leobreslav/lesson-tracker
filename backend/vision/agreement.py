"""
Сошлись ли два чтения одной полоски. Чистые функции, ни сети, ни базы.

Смысл всей затеи здесь. Один читатель ошибается молча — прочитанное «Misha»
выглядит ровно так же уверенно, как верное. Два читателя молча ошибаются
только вместе, а вместе они ошибаются редко: у распознавателя рукописного и у
языковой модели разная природа и разные промахи.

Поэтому сравнение отвечает не на вопрос «кто прав» — этого оно знать не может
и не пытается, — а на вопрос **«есть ли о чём спросить человека»**.

Два правила выведены из того, чем расхождение бывает на самом деле:

- **молчание — не возражение.** Пустое поле у одного из читателей значит «я
  этого не увидел», а не «там написано другое». Mathpix не разбирает половину
  плиток на бледном скане, модель не называет пустую клетку вовсе — и если
  считать это спором, спорной окажется каждая страница, а пометка, стоящая
  везде, не значит ничего;
- **в какую графу попало слово — не свидетельство.** То же правило, что и при
  сопоставлении с составом курса: подписываются «фамилия имя», а читатель
  может переставить графы местами. Поэтому имя с фамилией сравниваются парой
  слов целиком, а не по графам.
"""

from __future__ import annotations

import re

# Мелочь, которой чтения различаются без всякого смысла: регистр, точки,
# дефисы, «ё». Различие тут — это шум, а спор мы ищем настоящий.
JUNK = re.compile(r"[^\w\s]|_", re.UNICODE)


def words(*parts: str) -> tuple:
    """Имя и фамилия -> отсортированный набор слов, по которому и сверяем."""
    text = JUNK.sub(" ", " ".join(parts or ()).lower().replace("ё", "е"))
    return tuple(sorted(word for word in text.split() if word))


def compare(one: dict, two: dict) -> list[str]:
    """
    Два чтения -> список того, в чём они расходятся.

    Коды, а не текст: показывает их экран, а он говорит на двух языках.
    `name` — разошлись имена; `cell:N` — в клетке N у читателей разные цифры.
    Пустой список значит «спорить не о чем», и это самый частый ответ.

    Не ответивший читатель не спорит: `error` в чтении — это «меня не было»,
    а не «там написано другое».
    """
    if not one or not two:
        return []
    if one.get("error") or two.get("error"):
        return []

    out = []
    mine = words(one.get("first_name", ""), one.get("surname", ""))
    theirs = words(two.get("first_name", ""), two.get("surname", ""))
    if mine and theirs and mine != theirs:
        out.append("name")

    ours = one.get("values") or []
    yours = two.get("values") or []
    for place in range(min(len(ours), len(yours))):
        here, there = ours[place], yours[place]
        if here is not None and there is not None and here != there:
            out.append(f"cell:{place}")

    return out
