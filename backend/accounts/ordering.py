"""
В каком порядке идут люди в списке: фамилия, имя, адрес.

Правило одно на все списки, и лежит оно здесь затем, что иначе расходится.
Разошлось уже: журнал и посещаемость шли по фамилии, а таблица результатов
работы и список людей школы — по имени. Один и тот же класс выглядел
по-разному на соседних экранах, и учитель, сверяющий таблицу с бумажным
журналом, искал каждого заново: школьные списки ведутся по фамилии.

Порядок из трёх ступеней, и каждая нужна:

* **фамилия** — по ней класс знают и на бумаге, и на перекличке;
* **имя** — однофамильцы в классе не редкость (брат и сестра), и без второй
  ступени их порядок решал бы адрес почты, то есть случай;
* **адрес** — чтобы порядок был полным. У человека без имени и фамилии
  (приглашён, ещё не входил) других признаков нет, а неполный порядок
  перекладывает строки между двумя загрузками одной страницы.
"""


def by_surname(prefix: str = "") -> tuple[str, str, str]:
    """
    Поля для `order_by`: `by_surname()` у самих людей, `by_surname("student")`
    — у строки, которая на человека ссылается.
    """
    lead = f"{prefix}__" if prefix else ""
    return (f"{lead}last_name", f"{lead}first_name", f"{lead}email")
