"""
Кого этот контур пускает внутрь.

Один вопрос — «этому адресу сюда можно?» — и один ответ на все двери. Дверей
в приложение **две**: вход через Google (`/api/auth/google/`) и дев-дверь
браузерных тестов (`/api/test/login/`). Вторая существует не везде, но там,
где существует, она выдаёт токен **кому угодно по адресу**, без пароля и без
Google, — то есть равна первой по последствиям и обязана спрашивать то же
самое. Правило, написанное только у первой, оставило бы вторую открытой, и
выглядело бы это как «контур закрыт», пока кто-нибудь не наберёт второй
адрес.

**Пустой список значит «пускаем всех», и это не забытая настройка.** Так
устроен прод: школа приглашает людей, приглашение и есть допуск, а список
адресов в env-файле пришлось бы править при каждом новом учителе. Список
нужен ровно тем контурам, у которых своей публики нет вовсе, — стенду.

Отказ приходит **до создания учётки**: у allauth `pre_social_login` идёт
раньше авторегистрации, поэтому чужой вход не оставляет за собой
пользователя, которого потом надо убирать руками.

Раньше эту работу делал basic-auth в nginx, и делал он её плохо по
построению: на `/api/` пароль стоять не может (basic-auth и токен приложения
делят заголовок `Authorization`), то есть API стенда был открыт всегда, а
закрыта — только страница. Дверь, которую нельзя поставить там, где входят,
это не дверь.
"""

from django.conf import settings


class NotAllowedHereError(Exception):
    """Адрес не в списке допущенных этого контура."""

    def __init__(self, email: str = ""):
        super().__init__(email)
        self.email = email


def allowed_emails() -> frozenset[str]:
    """Список допущенных, приведённый к нижнему регистру. Пустой — значит всех."""
    return frozenset(
        address.strip().lower()
        for address in getattr(settings, "LOGIN_ALLOWED_EMAILS", [])
        if address.strip()
    )


def open_to_everyone() -> bool:
    """Контур без списка: заходит любой, кого пустил Google. Так живёт прод."""
    return not allowed_emails()


def may_enter(email: str | None) -> bool:
    if open_to_everyone():
        return True
    return (email or "").strip().lower() in allowed_emails()


def refuse_unless_allowed(email: str | None) -> None:
    """Поднять `NotAllowedHereError`, если этому адресу сюда нельзя."""
    if not may_enter(email):
        raise NotAllowedHereError(email or "")
