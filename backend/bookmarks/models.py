"""
Личный стол сотрудника: папка, в которой он держит нужное себе.

Единственная модель этого приложения — **папка**, а не закладка. Сами
закладки — это `files.Attachment`, у которого появился пятый владелец
(`bookmark_owner`): файл, ссылка и запись здесь ровно те же три вида
материала, что у урока, и заводить им вторую таблицу значило бы завести
второе хранилище файлов рядом с первым — со своей загрузкой, своей
дедупликацией и своим сносом осиротевших объектов. Разошлись бы они молча.

Владелец у стола — **человек**, и это единственное место в проекте, где так.
Личная форма доступа отсюда когда-то ушла целиком, и ушла по делу: план,
расписание и работы были личными потому, что курс могли вести двое, а когда
ведущий стал один, различаться перестало нечему. Здесь другой случай, и он
не про курс вовсе: «мои ссылки» не принадлежат ни курсу, ни школе — они
принадлежат тому, кто их сложил, и после его ухода из школы не достаются
никому. Поэтому и `CASCADE` на пользователе: стол уходит вместе с хозяином.

Папка — это **адрес внутри стола**, а не владелец лежащего в ней. Разница
та же, что у `Attachment.task` внутри работы ученика, и стоит она ровно
того, ради чего заведена: закладка переживает снос папки — уходит папка,
вещи ложатся на стол без папки, а не пропадают вместе с файлом. Сделай
папку владельцем, и «прибрался в папках» означало бы «удалил свои файлы».
"""

from django.conf import settings
from django.db import models


class Folder(models.Model):
    """
    Папка на личном столе: имя и порядок, больше ничего.

    Школы у неё нет намеренно, хотя всё остальное в проекте её несёт: школа
    известна по хозяину, а второе её хранение развело бы два ответа на один
    вопрос в день, когда человек переходит в другую школу.
    """

    owner = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        related_name="bookmark_folders",
        on_delete=models.CASCADE,
        verbose_name="owner",
    )
    title = models.CharField("title", max_length=120)
    position = models.PositiveIntegerField("position", default=0)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = "bookmark folder"
        verbose_name_plural = "bookmark folders"
        ordering = ("position", "id")
        indexes = [
            models.Index(fields=("owner", "position"), name="bookmark_folder_idx"),
        ]

    def __str__(self):
        return self.title
