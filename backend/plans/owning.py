"""
Чьё это дерево: курса или шаблона с полки.

План принадлежал ровно курсу, и `course_id` ходил по сервисам простым
числом. Владельцев стало двое, когда шаблон библиотеки перестал быть снимком
плана и стал правиться тем же экраном: программу пишут и для класса,
который в этом году не ведут, — а курса под такую программу нет и заводить
его незачем.

**Владелец выражен парой полей у самого узла**, а не признаком «вид записи».
Тот же приём, что у вложения с его шестью владельцами (`files/models.py`), и
по той же причине: принадлежность должна читаться из данных, а флаг «это
шаблонная строка» рядом с полем `course` однажды разойдётся с ним, и никто
не скажет, кому верить.

**Список владельцев написан один раз.** По нему собирается ограничение базы,
по нему выбирается уровень дерева и по нему же проверяется, что в родители не
взяли чужую тему. Перечисление по месту означало бы три списка, расходящихся
молча, — а забытый в ограничении владелец не запрещает ничего.
"""

import functools
import operator
from typing import NamedTuple

from django.db.models import Q

#: Кем бывает владелец узла: ровно один назван, остальные пусты.
OWNER_FIELDS = ("course", "template")


def owned_by(field: str) -> Q:
    """«Владелец ровно этот»: он назван, остальные пусты."""
    return Q(**{f"{name}__isnull": name != field for name in OWNER_FIELDS})


def exactly_one_owner() -> Q:
    """Условие ограничения: владелец есть, и он один."""
    return functools.reduce(operator.or_, (owned_by(name) for name in OWNER_FIELDS))


class PlanOwner(NamedTuple):
    """
    Владелец — полем и номером, без похода в базу.

    Номером, а не объектом, и это не экономия строчки: владельца спрашивают
    на каждом шаге правки — `level`, `reindex`, `place` зовутся по нескольку
    раз за один перенос строки, — и грузить ради ключа выборки курс из базы
    значило бы запрос на каждое движение мышью.
    """

    field: str
    id: int

    @property
    def lookup(self) -> dict:
        """`{поле_id: номер}` — этим и выбирается уровень дерева."""
        return {f"{self.field}_id": self.id}

    @property
    def is_template(self) -> bool:
        """Шаблон отличается от курса ровно там, где речь о датах и правах."""
        return self.field == "template"


def owner_of(node) -> PlanOwner:
    """
    Владелец узла — то из полей, которое названо.

    Пустой ответ здесь невозможен: «владелец ровно один» держит ограничение
    базы. Узел, ещё не сохранённый и не заполненный, — единственный случай, и
    отказ ему честнее пустоты: молчаливый `None` уехал бы в `filter()` и
    выбрал бы чужое дерево целиком.
    """
    for field in OWNER_FIELDS:
        value = getattr(node, f"{field}_id", None)
        if value is not None:
            return PlanOwner(field, value)

    raise ValueError("A plan node has no owner: name a course or a template.")
