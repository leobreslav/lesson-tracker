#!/usr/bin/env bash
#
# Браузерные тесты одной командой.
#
#   ./e2e.sh                     # весь набор (~8 минут)
#   ./e2e.sh --smoke             # дымовой: все экраны и ряды (~1 минута)
#   ./e2e.sh plan                # только файлы, чьё имя содержит «plan»
#   ./e2e.sh -g "перетаскивание" # по названию теста
#   ./e2e.sh --keep              # не гасить стек после прогона
#   ./e2e.sh --keep-dev          # не трогать стек разработки (см. ниже)
#
# Стек поднимается свой (docker-compose.e2e.yml): nginx с собранным бандлом,
# gunicorn, база в памяти. Никакого dev-сервера — ловим то, что ломается
# именно в сборке.

set -Eeuo pipefail

COMPOSE="docker compose -f docker-compose.e2e.yml"
KEEP=0
KEEP_DEV=0
PAUSED=0
ARGS=()

log()  { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
fail() { printf '\033[31mОшибка: %s\033[0m\n' "$*" >&2; exit 1; }

# Дымовой набор: два файла, которые обходят **все** экраны — маршруты и ряды
# контролов в обеих локалях. Ловит он ровно тот класс, ради которого
# браузерные тесты и заведены: ошибку в консоли, которую `vite build` не
# видит, и разъехавшуюся вёрстку. Полный набор ловит то же самое плюс
# поведение, и стоит вдесятеро дороже — поэтому он гоняется на GitHub (пуш в
# main и ночью), а этот здесь, при каждой правке.
SMOKE=(navigation controls)

for arg in "$@"; do
    case "$arg" in
        --keep)     KEEP=1 ;;
        --keep-dev) KEEP_DEV=1 ;;
        --smoke) ARGS+=("${SMOKE[@]}") ;;
        *)       ARGS+=("$arg") ;;
    esac
done

[ -f docker-compose.e2e.yml ] || fail "запускайте из корня репозитория"

#
# СТЕК РАЗРАБОТКИ УСТУПАЕТ МЕСТО, И ЭТО ЗАМЕР, А НЕ ОСТОРОЖНОСТЬ.
#
# У ноутбука восемь гигабайт, и делят их два стека: тот, в котором работают,
# и этот. Наружу теснота выходит не отказом, а **ложью**: `page.goto` не
# укладывается в свои 15 секунд, тест падает по таймауту — и падают каждый
# раз разные тесты, в областях, которых правка не касалась. Ни одного
# упавшего утверждения при этом нет.
#
# Замер, ради которого это написано: те же тесты со стеком разработки шли по
# 21 секунде и падали, с погашенным — по 3–6 секунд и проходили. Половина
# времени уходила на то, чтобы потом эту половину опровергать: перегнать
# упавшее поодиночке и увидеть, что всё зелено.
#
# Поэтому прогон гасит стек разработки сам и поднимает обратно — всегда, в
# том числе после отказа и Ctrl+C (`trap`). Гасит только если тот работал:
# поднимать чужой стек, которого не было, скрипт не вправе.
#
# `--keep-dev` отключает это: пригодится, когда в браузере рядом смотрят на
# dev-сервер, и лишние секунды дешевле потерянной страницы.
pause_dev() {
    [ "$KEEP_DEV" -eq 1 ] && return 0
    docker compose ps --status=running --quiet 2>/dev/null | grep -q . || return 0

    log "Уступаю память: гашу стек разработки"
    docker compose stop >/dev/null 2>&1 || true
    PAUSED=1
}

resume_dev() {
    [ "$PAUSED" -eq 1 ] || return 0

    log "Поднимаю стек разработки обратно"
    docker compose up -d >/dev/null 2>&1 || true
    # Контейнер, остановленный на паузе, обычным `up -d` поднимается не
    # всегда: фронтенд после `stop` выходит с кодом 127, и compose считает
    # его существующим. Пересоздание — единственное, что его чинит.
    for service in $(docker compose ps -a --status=exited --format '{{.Service}}' 2>/dev/null); do
        docker compose up -d --force-recreate "$service" >/dev/null 2>&1 || true
    done
}

cleanup() {
    # Чем кончился сам прогон — **первой строкой**, до всякой уборки.
    #
    # Ловушка `EXIT` в bash завершает скрипт статусом **последней команды в
    # ней самой**, а не тем, с которым в неё пришли. Уборка же почти всегда
    # успешна: `down` с `|| true`, поднятый обратно стек разработки — и любой
    # упавший прогон выходил нулём.
    #
    # Стоило это ровно того, ради чего скрипт написан: сборка фронтенда легла
    # с ошибкой разбора JSX, `up --build` честно вернул единицу, прогон не
    # начинался вовсе — а `./e2e.sh --smoke` отвечал «готово». Гейт, который
    # не умеет сказать «нет», хуже отсутствующего: на него ссылаются.
    local status=$?

    if [ "$KEEP" -eq 0 ]; then
        log "Гашу стек"
        $COMPOSE down --remove-orphans >/dev/null 2>&1 || true
    else
        printf '\nСтек оставлен: http://localhost:8080 (погасить — %s down)\n' "$COMPOSE"
    fi
    resume_dev
    exit "$status"
}
trap cleanup EXIT

pause_dev

log "Собираю и поднимаю прод-подобный стек"
# --build обязателен: фронтенд собирается в образе, и без пересборки тесты
# гоняли бы прошлый бандл, а именно его свежесть мы и проверяем
$COMPOSE up -d --build db backend frontend-build nginx

log "Прогоняю тесты"
# -T, когда терминала нет: в CI `docker compose run` без него спотыкается о
# «the input device is not a TTY». Локально флаг не ставим — с ним пропадает
# цвет и посекундный вывод Playwright, а смотрят на него именно глазами.
[ -t 1 ] && TTY=() || TTY=(-T)

# Зависимости ставятся отдельным шагом, а не командой сервиса: строку
# запуска мы переопределяем ниже (иначе некуда девать аргументы), и
# объявленный в compose `npm ci` до чистого клона не доезжает вовсе.
# Локально каталог уже есть, и шаг ничего не стоит; в CI и в облачной
# сессии без него playwright не находит @playwright/test и падает на
# разборе своего же конфига.
$COMPOSE run --rm -T e2e sh -c '[ -d node_modules/@playwright/test ] || npm ci'

$COMPOSE run --rm "${TTY[@]}" e2e npx playwright test "${ARGS[@]}"
