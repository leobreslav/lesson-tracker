#!/usr/bin/env bash
#
# Выкатка прода по ветке `production`: раз в несколько минут смотрит, не
# передвинулась ли она на origin, и если передвинулась — зовёт deploy.sh.
#
# Ставится в crontab прода:
#   */5 * * * * ~/lesson-tracker/scripts/prod-autodeploy.sh
#
# ЭТО НЕ АВТОВЫКАТКА. Стенд следит за origin/main и потому выкатывается сам
# после каждой задачи; прод следит за **отдельной веткой**, которая сама
# никуда не двигается. Решение выкатить осталось человеческим — сменилось
# только место, где оно принимается: было «запустить push-deploy.sh с
# ноутбука», стало «передвинуть production на github.com». Второе доступно с
# телефона и из любой сессии, а первое требовало той единственной машины, где
# лежит ssh-ключ.
#
# Почему опрос, а не Actions или вебхук — то же, что у стенда
# (scripts/staging-autodeploy.sh): обоим пришлось бы пустить снаружи внутрь,
# то есть положить ключ от боевой школы в секреты репозитория и открыть вход
# на сервер. Опрос не требует ничего: наружу ходит сам сервер, и ходит туда,
# куда и так ходит за кодом.
#
# ЧЕГО ЭТОТ ПУТЬ НЕ УМЕЕТ: возить `.env.prod`. Файл лежит вне git, и главная
# его копия — на ноутбуке. Меняли набор переменных — выкатка с телефона
# доедет с **прежним** env-файлом, а `VITE_GOOGLE_CLIENT_ID` вшивается в
# бандл на сборке. Тогда нужен ноутбук: `./scripts/sync-env.sh prod`, и
# только потом двигать ветку. Сверить, не разъехалось ли, —
# `./scripts/check-secrets.sh`.

set -Eeuo pipefail

REPO_DIR="$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)"
cd "$REPO_DIR"

BRANCH="production"
LOG="$HOME/.prod-autodeploy.log"
# Замок общий с push-deploy.sh: выкатка с ноутбука и выкатка по опросу могут
# совпасть по времени, и два `docker compose up` над одним стеком — это не
# гонка данных, а погашенный сайт. Имя замка знают оба, и другого способа
# позвать deploy.sh на проде нет.
LOCK="$HOME/.prod-deploy.lock"

say() { printf '%s  %s\n' "$(date '+%F %T')" "$*" >> "$LOG"; }

exec 9>"$LOCK"
flock -n 9 || { say "пропуск: выкатка уже идёт"; exit 0; }

# --- это точно прод? ---------------------------------------------------------
#
# Проверка написана в белый список: скрипт работает только там, где машина
# назвала себя боевым контуром. Неизвестное имя и пустой ответ — отказ, а не
# «наверное, прод». Цена ошибки здесь несимметрична: этот скрипт выкатывает
# без человека, и выкатить не туда хуже, чем не выкатить вовсе.
#
# Спрашиваем **двумя** способами по той же причине, что и
# contour_matches_machine в scripts/contours.sh: у прода строки
# COMPOSE_PROJECT_NAME в env-файле нет — он живёт на умолчании из
# compose-файла. Сторож, знающий только про env, на боевой машине молчал бы
# всегда, то есть ровно там, где он нужен.
#
# `|| true` в обоих — не косметика. При `set -o pipefail` отсутствующий
# .env.prod даёт sed код 2, а `head -1` закрывает трубу раньше времени и даёт
# SIGPIPE; `set -e` на присваивании убивает скрипт **до** единственной строки,
# которая объяснила бы, что произошло. Ровно этот молчаливый выход и поймал
# сторож scripts/test-prod-autodeploy.sh на первом же прогоне: чистая машина
# без env-файла выходила кодом 2 и не писала в лог ничего.
PROJECT="$(sed -n 's/^COMPOSE_PROJECT_NAME=//p' .env.prod 2>/dev/null | tail -n1 || true)"
if [ -z "$PROJECT" ]; then
    PROJECT="$(docker ps --format '{{.Names}}' 2>/dev/null |
        sed -n 's/-\(backend\|db\|nginx\)-[0-9]\+$//p' | sort -u | head -1 || true)"
fi
case "${PROJECT:-}" in
    lesson-tracker-prod) ;;
    *) say "ОТКАЗ: контур «${PROJECT:-не задан}» не похож на прод"; exit 1 ;;
esac

# --- на той ли ветке дерево? -------------------------------------------------
#
# deploy.sh тянет `git pull --ff-only` **текущую** ветку, а не ту, за которой
# мы следим. Если сервер оставили на main, сравнение шло бы с
# origin/production, а тянулся бы main — то есть прод выкатывал бы то, чего у
# него не просили, и ровно тогда, когда об этом никто не думает.
CURRENT="$(git rev-parse --abbrev-ref HEAD)"
if [ "$CURRENT" != "$BRANCH" ]; then
    say "ОТКАЗ: дерево на ветке «$CURRENT», а слежу я за «$BRANCH»"
    exit 1
fi

# --- есть ли что выкатывать --------------------------------------------------
#
# Отказ fetch'а должен быть виден: при `set -e` неудачная команда завершила бы
# скрипт молча, и «прод не обновляется» не отличить от «нечего обновлять».
# Жалуемся раз в час, иначе лог заплывёт на любой сетевой заминке.
if ! git fetch --quiet origin "$BRANCH" 2>/tmp/prod-fetch.err; then
    stamp_file="$HOME/.prod-autodeploy.fetchfail"
    now=$(date +%s)
    last=$(cat "$stamp_file" 2>/dev/null || echo 0)
    if [ $((now - last)) -gt 3600 ]; then
        say "НЕ МОГУ СВЯЗАТЬСЯ С GITHUB: $(head -1 /tmp/prod-fetch.err)"
        echo "$now" > "$stamp_file"
    fi
    exit 1
fi
rm -f "$HOME/.prod-autodeploy.fetchfail"

local_head="$(git rev-parse HEAD)"
remote_head="$(git rev-parse "origin/$BRANCH")"
[ "$local_head" = "$remote_head" ] && exit 0

# Откат ветки назад — это не выкатка, а `git pull --ff-only` на него и не
# согласится: скрипт упал бы в deploy.sh с невнятной ошибкой git. Говорим
# прямо, что произошло, и не трогаем работающий прод.
if ! git merge-base --is-ancestor "$local_head" "$remote_head"; then
    say "ОТКАЗ: origin/$BRANCH (${remote_head:0:8}) не является потомком
      текущего ${local_head:0:8} — ветку передвинули назад или переписали.
      Прод оставлен как есть; откат делается человеком с ноутбука."
    exit 1
fi

say "новый коммит ${remote_head:0:8} — выкатываю"

# deploy.sh делает всё остальное: git pull, сборку, перезапуск и проверку.
# Второго способа выкатывать в проекте быть не должно.
if ./deploy.sh >> "$LOG" 2>&1; then
    say "готово: $(git log --oneline -1)"
else
    say "ОШИБКА выкатки, прод остался на ${local_head:0:8}"
    exit 1
fi
