#!/usr/bin/env bash
#
# Файл окружения для разработки — если его ещё нет.
#
# `.env` в git не лежит и лежать не должен: тот же файл в боевом контуре
# держит пароль базы и токены R2. Но без него не поднимается **ничего** —
# compose объявляет `env_file: .env`, а `DEBUG` в settings.py объявлен без
# умолчания и роняет Django на старте.
#
# На своей машине файл пишут руками один раз и забывают. В облачной сессии
# писать некому: она начинается с чистого клона, и всё, чего нет в
# репозитории, там просто отсутствует. Поэтому репозиторий обязан уметь
# довести себя до рабочего состояния сам.
#
# Правило одно и оно важнее остальных: **существующий файл не трогается
# никогда**. В нём могут лежать настоящие ключи R2, и перезаписать их
# «свежими умолчаниями» значит отобрать у человека доступ к его же бакету.
#
# Ключей тут нет ни одного, и это не упущение:
#
#   R2_*        пусто → вложения не грузятся, seed_demo пропускает файлы с
#               предупреждением, а тесты и так ходят в память (config/testing.py);
#   GOOGLE_*    пусто → вход через Google не работает; входят дверью
#               E2E_TEST_LOGIN («войти как» в меню пользователя);
#   ANTHROPIC_  пусто → чтение сканов честно отказывает кодом ai_key_missing,
#               и это состояние покрыто тестом.
#
# Запускается сам, хуком SessionStart из .claude/settings.json.

set -Eeuo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

made=()

if [ ! -f .env ]; then
    # Ключ генерируется, а не берётся из примера: одинаковый SECRET_KEY во
    # всех клонах — это подписанные сессии, которые валидны в чужой копии.
    key="$(python3 -c 'import secrets; print(secrets.token_urlsafe(50))' 2>/dev/null \
        || head -c 40 /dev/urandom | base64 | tr -d '\n=/+')"

    cat > .env <<ENV
# Создан scripts/dev-env.sh. Правьте руками: скрипт готовый файл не трогает.
DEBUG=True
SECRET_KEY=$key
ALLOWED_HOSTS=localhost,127.0.0.1

POSTGRES_DB=lessons
POSTGRES_USER=lessons
POSTGRES_PASSWORD=lessons_local_pw
POSTGRES_HOST=db
POSTGRES_PORT=5432

GOOGLE_CLIENT_ID=
GOOGLE_CLIENT_SECRET=
CORS_ALLOWED_ORIGINS=http://localhost:5173

# Свой бакет для разработки. Пусто — вложения выключены целиком, и это
# рабочее состояние: seed_demo скажет об этом и посеет всё остальное.
R2_ACCESS_KEY_ID=
R2_SECRET_ACCESS_KEY=
R2_BUCKET_NAME=
R2_ENDPOINT_URL=

# Дверь для разработки: вход любым посеянным аккаунтом без Google. В
# .env.prod этой строки нет и быть не должно.
E2E_TEST_LOGIN=true

ANTHROPIC_API_KEY=

# Второй читатель шапки скана (Mathpix). Пусто — читает одна модель, как и
# раньше; с ключами читают двое, и расхождение показывается человеку.
MATHPIX_APP_ID=
MATHPIX_APP_KEY=
ENV
    # В этот файл рано или поздно вписывают настоящие ключи — тот же ключ
    # Anthropic, что на проде, секрет Google, токены R2. Права ставятся сразу:
    # доводить их потом руками значит не доводить. Проверено на себе — на
    # ноутбуке файл прожил так до аудита.
    chmod 600 .env
    made+=(".env")
fi

if [ ! -f frontend/.env ]; then
    # Vite вшивает переменную в бандл на сборке, поэтому файл нужен, даже
    # когда значения нет: без него сборка ругается на неопределённую
    # переменную, а кнопка Google всё равно не отрисуется без client_id.
    cat > frontend/.env <<'ENV'
# Создан scripts/dev-env.sh. Пусто — кнопки Google нет; входят дверью
# E2E_TEST_LOGIN («войти как» в меню пользователя).
VITE_GOOGLE_CLIENT_ID=
ENV
    chmod 600 frontend/.env
    made+=("frontend/.env")
fi

if [ ${#made[@]} -gt 0 ]; then
    printf 'Создан файл окружения: %s\n' "${made[*]}"
fi
