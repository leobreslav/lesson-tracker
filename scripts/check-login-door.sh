#!/usr/bin/env bash
#
# Замок на дверь контура: не даёт выкатить открытый вход туда, где входить
# должны не все.
#
#   scripts/check-login-door.sh [env-файл]      # по умолчанию .env.prod
#
# Зачем он есть. Пароль basic-auth убран: на `/api/` он стоять не мог в
# принципе (basic-auth и токен приложения делят заголовок Authorization), то
# есть закрывал он страницу, а не вход. Закрывает вход теперь список
# допущенных адресов — `LOGIN_ALLOWED_EMAILS`, разбор в
# `backend/accounts/door.py`.
#
# И вот тут появляется случай, который иначе прошёл бы молча. Стенд держит
# включённой дев-дверь `E2E_TEST_LOGIN`: ею ходит «войти как» в меню, и она
# выдаёт токен **кому угодно по адресу**, без Google и без пароля. Пока был
# пароль, снаружи её было не достать. Пароля нет — и контур с включённой
# дев-дверью и пустым списком это публичный вход учителем.
#
# Список живёт в env-файле, а env-файл лежит вне git и едет на сервер
# отдельно (`scripts/sync-env.sh`). Значит код и настройка приезжают на
# контур **порознь**, и порядок не гарантирован ничем. Замок делает опасный
# порядок невозможным: выкатка отказывается, контейнеры не тронуты, контур
# продолжает работать на прежнем коде — том, где пароль ещё стоит.
#
# Отказ, а не предупреждение: предупреждение в crontab читать некому.

set -Eeuo pipefail

ENV_FILE="${1:-.env.prod}"

fail() { printf '\033[31mОшибка: %s\033[0m\n' "$*" >&2; exit 1; }

[ -f "$ENV_FILE" ] || fail "нет файла $ENV_FILE"

# Значение из env-файла: последнее вхождение, без хвостового \r и без
# обрамляющих кавычек — их пишут, и Django их снимает, а сравнение с пустотой
# без них было бы неверным.
env_value() {
    local value
    value="$(sed -n "s/^$1=//p" "$ENV_FILE" | tail -n1)"
    value="${value%$'\r'}"
    value="${value%\"}"; value="${value#\"}"
    value="${value%\'}"; value="${value#\'}"
    printf '%s' "$value"
}

E2E="$(env_value E2E_TEST_LOGIN)"
ALLOWED="$(env_value LOGIN_ALLOWED_EMAILS)"

# Форм у «да» несколько, и env-читалка Django принимает их все. Список
# написан здесь, а не угадывается: незнакомое значение считается «нет»
# ровно потому, что и Django посчитает его так же.
case "$(printf '%s' "$E2E" | tr '[:upper:]' '[:lower:]' | tr -d '[:space:]')" in
    1|true|yes|on|y) DEV_DOOR=open ;;
    *)               DEV_DOOR=closed ;;
esac

if [ "$DEV_DOOR" = open ] && [ -z "$(printf '%s' "$ALLOWED" | tr -d '[:space:]')" ]; then
    fail "в $ENV_FILE включена дев-дверь E2E_TEST_LOGIN, а список допущенных пуст.

Дев-дверь выдаёт токен кому угодно по адресу — без Google и без пароля, — а
пароля на контуре больше нет. Выкатить это значит открыть контур учителем
всякому, кто знает адрес.

Добавьте в $ENV_FILE строку

    LOGIN_ALLOWED_EMAILS=вы@example.com

(через запятую, если входить должны несколько), увезите файл на контур
(./scripts/sync-env.sh staging) и повторите выкатку. Пока этого нет, контур
остаётся на прежнем коде — ничего не тронуто."
fi

exit 0
