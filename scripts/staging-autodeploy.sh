#!/usr/bin/env bash
#
# Автовыкатка стенда: раз в несколько минут смотрит, не появилось ли на
# origin/main нового коммита, и если появилось — зовёт deploy.sh.
#
# Ставится в crontab стенда:
#   */3 * * * * ~/apps/lesson-tracker/scripts/staging-autodeploy.sh
#
# Почему опрос, а не вебхук или GitHub Actions. Оба требуют пустить снаружи
# внутрь: Actions — ssh-ключ секретом в репозитории плюс открытый вход на
# сервер, вебхук — слушающий эндпоинт и проверку подписи. Опрос не требует
# ничего: наружу ходит сам стенд, и ходит он туда, куда и так ходит за кодом.
# Цена — задержка до интервала опроса, для стенда несущественная.
#
# Прод устроен так же (scripts/prod-autodeploy.sh) с одной разницей, и она
# существенная: он следит не за main, а за веткой `production`, которая сама
# никуда не двигается. Стенд подхватывает каждую задачу — он для того и
# заведён; прод ждёт, пока ветку передвинет человек.

set -Eeuo pipefail

REPO_DIR="$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)"
cd "$REPO_DIR"

LOG="$HOME/.staging-autodeploy.log"
LOCK="$HOME/.staging-autodeploy.lock"

say() { printf '%s  %s\n' "$(date '+%F %T')" "$*" >> "$LOG"; }

# Замок: выкатка идёт дольше интервала опроса, и второй запуск поверх первого
# сносил бы стек из-под него. flock снимается сам вместе с процессом, в том
# числе если тот убит.
exec 9>"$LOCK"
flock -n 9 || { say "пропуск: выкатка уже идёт"; exit 0; }

# --- защита от запуска на боевом контуре -------------------------------------
# Та же проверка, что в staging-seed.sh, и по той же причине: автоматическая
# выкатка без человека на проде — не то, о чём просили.
# `|| true`: без env-файла sed даёт код 2, pipefail его пропускает наружу, и
# set -e убивает скрипт до строки «ОТКАЗ» — то есть молча.
PROJECT="$(sed -n 's/^COMPOSE_PROJECT_NAME=//p' .env.prod 2>/dev/null | tail -n1 || true)"
case "${PROJECT:-}" in
    *staging*|*stand*|*test*) ;;
    *) say "ОТКАЗ: контур «${PROJECT:-не задан}» не похож на стенд"; exit 1 ;;
esac

# --- есть ли что выкатывать --------------------------------------------------
# git fetch дёшев и не трогает рабочее дерево; сравниваем то, что есть, с тем,
# что приехало. Пока они совпадают, не запускается ничего — иначе стенд
# пересобирался бы каждые три минуты.
# Отказ fetch'а должен быть виден. При `set -e` неудачная команда завершает
# скрипт молча: в логе не появляется ничего, и «стенд не обновляется» не
# отличить от «нечего обновлять». Проверено жизнью — GitHub на пару минут
# перестал принимать ssh, и автовыкатка эти минуты падала беззвучно.
#
# Про частоту: жалуемся раз в час, а не каждые три минуты, иначе лог
# заплывёт двадцатью строками в час на любой сетевой заминке.
if ! git fetch --quiet origin main 2>/tmp/staging-fetch.err; then
    stamp_file="$HOME/.staging-autodeploy.fetchfail"
    now=$(date +%s)
    last=$(cat "$stamp_file" 2>/dev/null || echo 0)
    if [ $((now - last)) -gt 3600 ]; then
        say "НЕ МОГУ СВЯЗАТЬСЯ С GITHUB: $(head -1 /tmp/staging-fetch.err)"
        echo "$now" > "$stamp_file"
    fi
    exit 1
fi
rm -f "$HOME/.staging-autodeploy.fetchfail"

local_head="$(git rev-parse HEAD)"
remote_head="$(git rev-parse origin/main)"

# Упавшая выкатка обязана повториться, и без этой отметки она не повторялась.
#
# `deploy.sh` тянет код **сам**, и падение случается уже после `git pull` —
# значит дерево стоит на origin/{branch}, и следующий тик выходит на строке выше
# как «нечего выкатывать». Снаружи это выглядит хуже всего: причину устранили,
# а контур молчит до следующего чужого коммита.
#
# Поймано на замке двери (scripts/check-login-door.sh): он отказывает, пока в
# env-файле нет списка допущенных, — и без отметки контур не выкатился бы и
# после того, как список туда добавили. Но дыра общая: так же вело себя любое
# падение сборки.
FAILED_MARK="$HOME/.staging-autodeploy.failed"
if [ "$local_head" = "$remote_head" ] && [ ! -f "$FAILED_MARK" ]; then
    exit 0
fi
if [ "$local_head" = "$remote_head" ]; then
    say "прошлая выкатка упала — пробую снова на ${local_head:0:8}"
fi

say "новый коммит ${remote_head:0:8} — выкатываю"

# deploy.sh делает всё остальное: git pull, сборку, перезапуск и проверку.
# Второго способа выкатывать в проекте быть не должно.
if ./deploy.sh >> "$LOG" 2>&1; then
    rm -f "$FAILED_MARK"
    say "готово: $(git log --oneline -1)"
else
    # отметка ставится **после** попытки, а не до: до неё выкатка ещё могла
    # и не начаться, а повторять надо именно неудавшуюся
    : > "$FAILED_MARK"
    say "ОШИБКА выкатки, стенд остался на ${local_head:0:8} — повторю на следующем тике"
    exit 1
fi
