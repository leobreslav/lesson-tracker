#!/usr/bin/env bash
#
# Что стоило проверить до первой правки — проверяется само, на старте сессии.
#
# Работа над проектом идёт из двух мест: с ноутбука и из облачной сессии.
# Облако тянет само — оно начинается с чистого клона, — а обратно нет: оно
# пушит в свою ветку и приезжает пул-реквестом. Влили PR, вернулись на
# ноутбук — и дерево отстало.
#
# **Забытый `git pull` сам по себе безобиден**: пуш поверх чужого git не даст,
# и это громко. Скрипт заведён ради двух тихих случаев:
#
# - **правка по устаревшему тексту.** `CLAUDE.md` и правила областей правятся
#   почти в каждой задаче; открыть переписанный файл, не зная об этом, значит
#   получить конфликт в связной прозе — самый неприятный род конфликта;
# - **миграция, приехавшая от другого исполнителя.** Тут `pull` мало: её надо
#   применить к своей долгоживущей базе. Ни один набор тестов этого не
#   поймает — все они поднимают базу с нуля. Выглядит как 500 в браузере на
#   пустом месте при трёх зелёных прогонах.
#
# Скрипт **ничего не делает молча**: он не тянет, не мигрирует и не трогает
# рабочее дерево. Он только говорит. Автоматический `pull` поверх незакоммиченной
# работы был бы ровно тем сюрпризом, от которого тут и защищаются.
#
# Сети может не быть, стек может быть погашен, каталог может оказаться не
# репозиторием — всё это не повод падать: сторож на старте сессии обязан быть
# незаметным, когда сказать нечего.

cd "${CLAUDE_PROJECT_DIR:-$(dirname "$(readlink -f "$0")")/..}" 2>/dev/null || exit 0
git rev-parse --git-dir >/dev/null 2>&1 || exit 0

say() { printf '%s\n' "$*"; }

# --- отстали ли от origin/main ------------------------------------------------
# Таймаут обязателен: без сети `git fetch` висит, а вместе с ним и старт сессии.
if timeout 10 git fetch --quiet origin main 2>/dev/null; then
    behind="$(git rev-list --count HEAD..origin/main 2>/dev/null || echo 0)"
    if [ "${behind:-0}" -gt 0 ]; then
        say "⚠ Дерево отстаёт от origin/main на $behind коммит(ов) — работа из облака уже влита."
        say "  Перед первой правкой: git pull --ff-only"
        # Миграции среди приехавшего — отдельная беда: их надо применить к
        # долгоживущей базе разработки, и это единственная база, которая
        # умеет отставать.
        migrations="$(git diff --name-only HEAD..origin/main 2>/dev/null |
            grep -c '/migrations/.*\.py$' || true)"
        [ "${migrations:-0}" -gt 0 ] &&
            say "  Среди них миграции ($migrations шт.): после pull нужен migrate."
    fi
fi

# --- не отстала ли dev-база от уже вытянутого кода ----------------------------
# Только если стек поднят: спрашивать погашенный контейнер бессмысленно, а
# поднимать его ради проверки — тем более.
if docker compose ps --status running --services 2>/dev/null | grep -qx backend; then
    unapplied="$(docker compose exec -T backend python manage.py showmigrations --plan \
        < /dev/null 2>/dev/null | grep -c '^\[ \]' || true)"
    if [ "${unapplied:-0}" -gt 0 ]; then
        say "⚠ В базе разработки не применено миграций: $unapplied."
        say "  docker compose exec backend python manage.py migrate"
    fi
fi

exit 0
