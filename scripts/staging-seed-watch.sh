#!/usr/bin/env bash
#
# Пересев стенда по просьбе, пришедшей веткой.
#
# Ставится в crontab стенда рядом с автовыкаткой:
#   */3 * * * * ~/apps/lesson-tracker/scripts/staging-seed-watch.sh
#
# ЗАЧЕМ. Пересев умеет ровно одна машина — та, где лежит ssh-ключ. Облачная
# сессия начинается с чистого клона, ключа там нет и быть не должно, а
# посмотреть свежее глазами на посеянных данных хочется именно оттуда: работа
# теперь идёт и из облака, и с телефона. Тот же разрыв уже закрыт для выкатки
# (scripts/ship.sh двигает ветки через gh, контуры подтягивают их сами), и
# здесь применён ровно тот же приём — второго способа заводить не пришлось.
#
# ПРОСЬБА — ЭТО КОММИТ НА ВЕТКЕ `staging-seed`. Дерево у него то же, что у
# main; смысл несёт **сообщение**, первая строка которого читается как
# «seed: <аргументы seed_demo>». Отсюда три свойства, которых не даёт
# ни метка, ни просто передвинутая ветка:
#
#   * каждая просьба — новый объект, поэтому «пересей ещё раз» отличимо от
#     «уже сеяли», даже когда main с тех пор не двигался;
#   * аргументы едут вместе с просьбой, а не лежат где-то на сервере;
#   * `git log origin/staging-seed` на github.com — это история пересевов:
#     кто просил, когда и с чем. Отдельного журнала заводить не нужно.
#
# ИСПОЛНЯЕТСЯ ПРОСЬБА ОДИН РАЗ. Отметка о просьбе пишется **до** посева, а не
# после, и это выбор, а не небрежность: упавший посев, записанный как
# неисполненный, повторялся бы каждые три минуты — то есть сносил бы базу по
# кругу, пока кто-нибудь не заметит. Не вышло — в логе сказано почему, и
# просьба посылается заново.
#
# ЧЕГО ЭТОТ ПУТЬ НЕ УМЕЕТ — того же, чего не умеет выкатка веткой: возить
# `.env.prod`. Файл лежит вне git, главная копия на ноутбуке. Значит новую
# переменную из облака не завезти, и посев тут ни при чём.

set -Eeuo pipefail

REPO_DIR="$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)"
cd "$REPO_DIR"

BRANCH="staging-seed"
LOG="$HOME/.staging-seed.log"
STAMP="$HOME/.staging-seed.last"
# Замок общий с автовыкаткой, и это важнее, чем кажется: посев перезапускает
# backend дважды (включает отладку и возвращает обратно), а выкатка в это же
# время пересобирает стек. Два хозяина у одного стека — не гонка данных, а
# погашенный стенд. Один замок значит «стенд занят», кем бы он ни был занят.
LOCK="$HOME/.staging-autodeploy.lock"

# Аргументы, которые берутся, когда просьба пришла без них. Живут в файле
# контура: адрес человека, которого надо сделать администратором школы, — это
# свойство стенда, а не просьбы, и облако его знать не обязано.
DEFAULT_ARGS_VAR="STAGING_SEED_ARGS"
FALLBACK_ARGS="--flush"

say() { printf '%s  %s\n' "$(date '+%F %T')" "$*" >> "$LOG"; }

exec 9>"$LOCK"
flock -n 9 || { say "пропуск: стенд занят"; exit 0; }

# --- это точно стенд? --------------------------------------------------------
# Тот же белый список, что в staging-seed.sh и staging-autodeploy.sh, и по той
# же причине: скрипт сносит базу без человека перед экраном. Забытая переменная
# здесь значит отказ, а не «наверное, стенд».
PROJECT="$(sed -n 's/^COMPOSE_PROJECT_NAME=//p' .env.prod 2>/dev/null | tail -n1 || true)"
case "${PROJECT:-}" in
    *staging*|*stand*|*test*) ;;
    *) say "ОТКАЗ: контур «${PROJECT:-не задан}» не похож на стенд"; exit 1 ;;
esac

# --- пришла ли просьба -------------------------------------------------------
#
# Спрашиваем `ls-remote`, а не `fetch`: ветки может не быть вовсе — до первой
# просьбы её и нет, — и `fetch` на несуществующий ref отвечает ошибкой, которую
# пришлось бы отличать от настоящей сетевой. Здесь разница видна сразу: пустой
# ответ — просьб не было, ненулевой код — не дозвонились.
#
# Про частоту жалоб: раз в час, как у автовыкатки. Иначе лог заплывёт двадцатью
# строками в час на любой сетевой заминке, и в нём перестанут искать.
if ! remote="$(git ls-remote origin "refs/heads/$BRANCH" 2>/tmp/staging-seed-fetch.err)"; then
    stamp_file="$HOME/.staging-seed.fetchfail"
    now=$(date +%s)
    last=$(cat "$stamp_file" 2>/dev/null || echo 0)
    if [ $((now - last)) -gt 3600 ]; then
        say "НЕ МОГУ СВЯЗАТЬСЯ С GITHUB: $(head -1 /tmp/staging-seed-fetch.err)"
        echo "$now" > "$stamp_file"
    fi
    exit 1
fi
rm -f "$HOME/.staging-seed.fetchfail"

sha="$(printf '%s' "$remote" | cut -f1)"
[ -n "$sha" ] || exit 0                                   # просьб ещё не было

last="$(cat "$STAMP" 2>/dev/null || true)"
[ "$sha" = "$last" ] && exit 0                            # эту уже исполнили

if ! git fetch --quiet origin "$BRANCH" 2>>"$LOG"; then
    say "ОШИБКА: не смог забрать $BRANCH"
    exit 1
fi

subject="$(git log -1 --format=%s FETCH_HEAD)"

# Отметка ставится здесь — до разбора и до посева. Дальше любой исход, включая
# отказ и падение, оставляет просьбу исполненной: повторять её самостоятельно
# скрипт не должен ни при каком раскладе.
echo "$sha" > "$STAMP"

# --- что именно просят -------------------------------------------------------
case "$subject" in
    "seed:") args="" ;;
    "seed: "*) args="${subject#seed: }" ;;
    *)
        say "ОТКАЗ: ${sha:0:8} — сообщение «$subject» не похоже на просьбу.
      Первая строка должна начинаться с «seed:»; просьбы шлёт
      ./scripts/ship.sh --reseed"
        exit 1
        ;;
esac

if [ -z "${args// }" ]; then
    args="$(sed -n "s/^$DEFAULT_ARGS_VAR=//p" .env.prod 2>/dev/null | tail -n1 || true)"
    args="${args:-$FALLBACK_ARGS}"
    source_of_args="умолчание контура"
else
    source_of_args="просьба"
fi

# Аргументы приходят строкой из сообщения коммита, и подставляются они без
# кавычек — значит список допустимого лучше назвать явно. Права это не даёт
# никаких (двинуть ветку может лишь тот, у кого есть доступ на запись в
# репозиторий), но опечатка вроде `--flash` должна кончаться внятным отказом в
# логе, а не поведением seed_demo по умолчанию на живом стенде.
for a in $args; do
    case "$a" in
        --flush|--rich|--minimal|--root) ;;
        --email=*@*) ;;
        *)
            say "ОТКАЗ: ${sha:0:8} — аргумент «$a» не из списка разрешённых
      (--flush, --rich, --minimal, --root, --email=кто@где)"
            exit 1
            ;;
    esac
done

say "просьба ${sha:0:8} ($source_of_args): seed_demo $args"

# Сеет staging-seed.sh — он и только он: окно с DEBUG=True, проверка контура и
# возврат отладки ловушкой на выходе живут там, и второго такого места быть не
# должно.
if ./scripts/staging-seed.sh $args >> "$LOG" 2>&1; then
    say "готово: ${sha:0:8}"
else
    say "ОШИБКА посева по просьбе ${sha:0:8} — смотрите выше в этом логе"
    exit 1
fi
