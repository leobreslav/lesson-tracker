#!/usr/bin/env python3
"""
Сторож у платного API: команда, способная потратить деньги, не проходит молча.

Читает на stdin описание команды от Claude Code (хук `PreToolUse`) и, если
команда может уйти в Anthropic, отвечает решением `ask` — то есть превращает
её в вопрос человеку вместо тихого запуска. Правило целиком — в CLAUDE.md,
«Живые запросы к Anthropic».

**Почему хук, а не только правило.** Правило уже было записано, и его же
нарушил тот, кто писал: чтение сканов проверялось «на десять секунд» через
`manage.py shell`, и деньги ушли. `docker compose exec` стоит в разрешённых
без вопроса, тест-раннер обнуляет ключ только под `manage.py test` — значит
на отладочном пути не было ничего вовсе.

**Почему `ask`, а не `deny`.** Отказ пришлось бы обходить снятием хука, и
тогда снимали бы его заранее «чтобы не мешал». Вопрос же достижим: человек
видит команду и причину и отвечает. Это ровно формулировка правила —
разрешение спрашивается каждый раз, но оно возможно.

**Что ловим.** Не слова, а формы запуска: искать `read_header` по коду
безопасно и вопроса не вызывает.

- `manage.py shell` — **всегда**, даже без единого упоминания Anthropic:
  скрипт приезжает на stdin, и по самой команде не видно, что он делает.
  Ровно так деньги и потратили;
- обращение к `api.anthropic.com` из `curl`/`wget`;
- запуск питона (`-c`, `-m`, файл), в командной строке которого поминается
  клиент чтения.

**Чего не ловим, и это честно.** Хук читает текст команды, поэтому вызов,
спрятанный в файле с безобидным именем и запущенный без этих признаков,
пройдёт. Сторож закрывает **случайную** трату — ту, что была, — а не
намеренный обход. `jq` тут не используется намеренно: на машине разработчика
его нет, и хук на `jq` молча не срабатывал бы.
"""

import json
import re
import sys

# (образец, чем объяснить человеку). Порядок важен: первое совпадение и
# отвечает, поэтому сверху самая частая форма.
SPEND_SHAPES = [
    (
        r"manage\.py\s+shell",
        "`manage.py shell` получает скрипт на stdin — по команде не видно, "
        "что он выполнит, а чтение сканов оттуда стоит денег",
    ),
    (
        r"\b(curl|wget|http|httpie)\b[^|;&]*api\.anthropic\.com",
        "прямое обращение к api.anthropic.com",
    ),
    (
        r"python[0-9.]*\s+(-c|-m|[^\s|;&]*\.py)"
        r"[^|;&]*(vision|anthropic|read_header|read_questions)",
        "запуск кода, который зовёт клиента Anthropic",
    ),
]


def verdict(command: str) -> str | None:
    for pattern, why in SPEND_SHAPES:
        if re.search(pattern, command, re.IGNORECASE):
            return why
    return None


def main() -> int:
    try:
        payload = json.load(sys.stdin)
    except (json.JSONDecodeError, ValueError):
        # Не поняли ввод — молчим. Сломать работу сторож не должен.
        return 0

    command = (payload.get("tool_input") or {}).get("command") or ""
    why = verdict(command)
    if not why:
        return 0

    reason = (
        f"Запрос в Anthropic тратит деньги владельца ключа: {why}. "
        "По правилу проекта (CLAUDE.md, «Живые запросы к Anthropic») на это "
        "нужно явное разрешение человека — каждый раз."
    )
    print(
        json.dumps(
            {
                "hookSpecificOutput": {
                    "hookEventName": "PreToolUse",
                    "permissionDecision": "ask",
                    "permissionDecisionReason": reason,
                },
                # Сообщение дублирует причину нарочно: если под режимом без
                # вопросов `ask` окажется молчаливым, человек всё равно
                # увидит, что происходит.
                "systemMessage": f"⚠ Команда может потратить деньги в Anthropic: {why}",
            },
            ensure_ascii=False,
        )
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
