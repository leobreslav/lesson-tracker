#!/usr/bin/env python3
"""
Сторож у платного API: команда, способная потратить деньги, не проходит молча.

Читает на stdin описание команды от Claude Code (хук `PreToolUse`) и, если
команда может уйти в Anthropic, отвечает решением `ask` — то есть превращает
её в вопрос человеку вместо тихого запуска. Правило целиком — в CLAUDE.md,
«Живые запросы к Anthropic».

**Почему хук, а не только правило.** Правило уже было записано, и его же
нарушил тот, кто писал: чтение сканов проверялось «на десять секунд» через
`manage.py shell`, и деньги ушли. `docker compose exec` стоит в разрешённых
без вопроса, тест-раннер обнуляет ключ только под `manage.py test` — значит
на отладочном пути не было ничего вовсе.

**Почему `ask`, а не `deny`.** Отказ пришлось бы обходить снятием хука, и
тогда снимали бы его заранее «чтобы не мешал». Вопрос же достижим: человек
видит команду и причину и отвечает. Это ровно формулировка правила —
разрешение спрашивается каждый раз, но оно возможно.

**Что ловим.** Не слова, а формы запуска: искать `read_header` по коду
безопасно и вопроса не вызывает.

- `manage.py shell` **без `-c`** — всегда, даже без единого упоминания
  Anthropic: скрипт приезжает на stdin, и по самой команде не видно, что он
  делает. Ровно так деньги и потратили;
- `manage.py shell -c «код»` — только если в самом коде есть вызов. Здесь
  причина «не видно, что выполнит» отпадает: программа стоит в командной
  строке и видна целиком, как у `python -c`. Пока это различие не делалось,
  сторож спрашивал про чтение списка пользователей — то есть про то, где
  тратить нечего;
- обращение к `api.anthropic.com` из `curl`/`wget`;
- запуск питона (`-c`, `-m`, файл), в командной строке которого поминается
  клиент чтения.

**Чего не ловим, и это честно.** Хук читает текст команды, поэтому вызов,
спрятанный в файле с безобидным именем и запущенный без этих признаков,
пройдёт. Сторож закрывает **случайную** трату — ту, что была, — а не
намеренный обход. `jq` тут не используется намеренно: на машине разработчика
его нет, и хук на `jq` молча не срабатывал бы.
"""

import json
import re
import sys

# Что именно **тратит деньги**. Не слово «anthropic» — его поминают всюду, от
# ENV_VARS.md до правки конфига, — а вызов.
#
# Первая версия ловила голое `anthropic|vision`, и на этом обожглись трижды за
# сессию: правка файла, где в тексте стоит `ANTHROPIC_API_KEY`, вызывала
# вопрос про трату. Имя переменной не запрос; `printenv ANTHROPIC_API_KEY`
# денег не стоит, а `Anthropic(...)` стоит.
# Из `vision` наружу ходят только `client` и `services`. `prices` считает
# стоимость по таблице и не отправляет ничего — CLAUDE.md разрешает его прямо,
# и голый `from vision import` ловил бы разрешённое.
CALLS = (
    r"(vision\.client|vision\.services"
    r"|from\s+vision\s+import\s+(client|services)"
    r"|read_header\s*\(|read_questions\s*\("
    r"|Anthropic\s*\(|messages\.create"
    r"|api\.anthropic\.com)"
)

# Нужен **исполнитель** перед `manage.py`, а не упоминание. Иначе сторож ловит
# собственное описание: сообщение коммита про него самого содержит слова
# «manage.py shell» и целиком уезжает в командную строку `git commit`. Так и
# вышло — дважды, и оба раза это списали на оборвавшуюся сеть.
SHELL = r"(python[0-9.]*|\./)\s*manage\.py\s+shell\b"

# Флаг, после которого программа лежит в самой команде, а не приезжает на
# stdin. Django принимает обе формы, длинную и короткую.
INLINE = r"\s+(-c|--command)\b"

# (образец, чем объяснить человеку). Порядок важен: первое совпадение и
# отвечает, поэтому сверху самая частая форма.
SPEND_SHAPES = [
    (
        # Без `-c` судить не по чему: тело придёт на stdin, и в команде его
        # нет. Спрашиваем всегда — ровно так деньги и потратили.
        rf"{SHELL}(?!{INLINE})",
        "`manage.py shell` получает скрипт на stdin — по команде не видно, "
        "что он выполнит, а чтение сканов оттуда стоит денег",
    ),
    (
        # `-c "$SCRIPT"` или `-c "$(cat …)"`: флаг есть, а кода всё равно не
        # видно — его подставит шелл. Значит вернулись к первому случаю.
        rf"{SHELL}{INLINE}[^\n]*\$",
        "`manage.py shell -c` получает код подстановкой — по команде не "
        "видно, что он выполнит",
    ),
    (
        # Код виден целиком, поэтому судим по нему, как у `python -c`.
        rf"{SHELL}{INLINE}[\s\S]*{CALLS}",
        "`manage.py shell -c` выполняет код, который зовёт клиента Anthropic",
    ),
    (
        r"\b(curl|wget|http|httpie)\b[^|;&]*api\.anthropic\.com",
        "прямое обращение к api.anthropic.com",
    ),
    (
        rf"python[0-9.]*\s+(-c|-m|[^\s|;&]*\.py)[^|;&]*{CALLS}",
        "запуск кода, который зовёт клиента Anthropic",
    ),
    (
        # Питон, читающий программу со stdin: `python3 - <<'PY' … PY`. После
        # исполнителя стоит `-`, а не `-c` и не имя файла, поэтому прошлое
        # правило его не видело — а это самый короткий путь к трате из тех,
        # что пишутся на ходу.
        rf"python[0-9.]*\s+-\s*<<[^\n]*\n[\s\S]*?{CALLS}",
        "программа приходит питону со stdin и зовёт клиента Anthropic",
    ),
]


# Кто исполняет тело heredoc, а кто просто несёт его как текст.
INTERPRETERS = re.compile(r"\b(python[0-9.]*|bash|sh|zsh|node|ruby|perl)\b")

HEREDOC = re.compile(r"<<-?\s*(['\"]?)([A-Za-z_][A-Za-z0-9_]*)\1")


def executable_text(command: str) -> str:
    """
    Оставляет от команды то, что действительно **выполнится**.

    Разница не формальная. `git commit -F - <<'MSG' … MSG` несёт сообщение
    коммита, и в нём совершенно законно поминаются опасные формы — например,
    в описании этого самого сторожа. Данные это, а не код: git ничего из них
    не запустит и до Anthropic не дойдёт никогда.

    А `python3 - <<'PY' … PY` — ровно наоборот: тело и есть программа, и
    выкинуть его значило бы ослепить сторож на самом коротком пути к трате.

    Поэтому решает **команда перед heredoc**: интерпретатор — тело смотрим,
    что угодно другое — тело выбрасываем. Без этого различения сторож
    срабатывал на собственном описании, дважды за одну сессию, и оба раза
    отказ списали на оборвавшуюся сеть.
    """
    match = HEREDOC.search(command)
    if not match:
        return command

    head = command[: match.start()]
    if INTERPRETERS.search(head):
        return command  # тело исполняется — смотрим целиком

    # Тело — данные. Оставляем только то, что стоит вокруг heredoc: сама
    # команда и всё, что идёт после закрывающего слова.
    delimiter = match.group(2)
    body_and_tail = command[match.end():]
    closing = re.search(rf"^\s*{re.escape(delimiter)}\s*$", body_and_tail, re.M)
    tail = body_and_tail[closing.end():] if closing else ""
    return head + tail


def verdict(command: str) -> str | None:
    # Проверка самого сторожа — не трата. Ей приходится содержать те самые
    # формы, которые он ловит, иначе проверять нечего; без этого исключения
    # сторож нельзя испытать, не потревожив человека.
    #
    # Дыры это не открывает больше, чем уже названо в докстринге: он и так
    # закрывает случайную трату, а не намеренный обход.
    if "guard-anthropic-spend" in command:
        return None

    text = executable_text(command)
    for pattern, why in SPEND_SHAPES:
        if re.search(pattern, text, re.IGNORECASE):
            return why
    return None


def main() -> int:
    try:
        payload = json.load(sys.stdin)
    except (json.JSONDecodeError, ValueError):
        # Не поняли ввод — молчим. Сломать работу сторож не должен.
        return 0

    command = (payload.get("tool_input") or {}).get("command") or ""
    why = verdict(command)
    if not why:
        return 0

    reason = (
        f"Запрос в Anthropic тратит деньги владельца ключа: {why}. "
        "По правилу проекта (CLAUDE.md, «Живые запросы к Anthropic») на это "
        "нужно явное разрешение человека — каждый раз."
    )
    print(
        json.dumps(
            {
                "hookSpecificOutput": {
                    "hookEventName": "PreToolUse",
                    "permissionDecision": "ask",
                    "permissionDecisionReason": reason,
                },
                # Сообщение дублирует причину нарочно: если под режимом без
                # вопросов `ask` окажется молчаливым, человек всё равно
                # увидит, что происходит.
                "systemMessage": f"⚠ Команда может потратить деньги в Anthropic: {why}",
            },
            ensure_ascii=False,
        )
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
