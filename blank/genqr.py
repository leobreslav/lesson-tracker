import qrcode

# Что закодировано: поколение бланка и роль листа.
#
# **Поколение обязано быть в самом коде.** Лист живёт в кабинете год, и когда
# бланк сменится, старые и новые лягут вперемешку — а читать их надо по разной
# геометрии. Добавить номер задним числом нельзя: на напечатанной тысяче листов
# его не будет. Роль (`A` — answer) заведена той же строкой и по той же
# причине: место под будущий лист другого назначения стоит ноль сейчас и не
# существует потом.
#
# Алфавитно-цифровой режим QR (0-9 A-Z и `$%*+-./:`) — самый плотный из тех,
# что нас устраивают: шесть символов влезают в версию 1, то есть в матрицу 21
# на 21 вместо прежних 25.
PAYLOAD = "LT/2/A"

# Коррекция M вместо H, и это размен в нашу пользу.
#
# H держит потерю до 30% модулей и стоит четырёх лишних рядов. Стойкость эта
# нужна коду, который читают с мятой этикетки; наш печатают лазером на белой
# бумаге с тихой зоной вокруг. Освободившиеся ряды уходят в **размер модуля**,
# а он и есть то, чем код читается: чем крупнее модуль, тем больше пикселей на
# него приходится в скане и тем терпимее код к промаху выпрямления.
q = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M, box_size=1, border=0)
q.add_data(PAYLOAD)
q.make(fit=True)
m = q.get_matrix()
n = len(m)

fills = []
for y, row in enumerate(m):
    x = 0
    while x < n:
        if row[x]:
            x2 = x
            while x2 + 1 < n and row[x2 + 1]:
                x2 += 1
            fills.append(f"\\fill ({x},{n-1-y}) rectangle ({x2+1},{n-y});")
            x = x2 + 1
        x += 1

head = f"""% СГЕНЕРИРОВАНО, правится не здесь — см. README, раздел «QR».
%
% Содержимое постоянное: {PAYLOAD} — поколение бланка и роль листа. Про ученика,
% курс и школу не говорит ничего, и это условие, а не ограничение: лист один на
% всех и навсегда (`README.md`, первый раздел).
%
% Ради поколения он и стоит: тысяча листов живёт в кабинете год, и когда бланк
% сменится, старые и новые будут лежать вперемешку, а читать их надо по разной
% геометрии. Плюс страница, на которой его нет вовсе, — не наш лист, и этим
% размечается пачка.
%
% Матрица вписана готовой: она никогда не меняется, а пакета qrcode в образе
% нет. Уровень коррекции M — стойкости хватает лазерной печати на белой бумаге,
% а сэкономленные ряды ушли в размер модуля.
% Размер: {n}x{n} модулей; аргумент команды — сторона на бумаге.
\\newcommand{{\\blankqr}}[1]{{%
\\begin{{tikzpicture}}[x=#1/{n},y=#1/{n}]
"""
tail = "\\end{tikzpicture}}\n"
open("/w/qr_v1.tex", "w", encoding="utf-8").write(head + "\n".join(fills) + "\n" + tail)
print(f"{n}x{n} модулей, версия {q.version}, заливок {len(fills)}")
